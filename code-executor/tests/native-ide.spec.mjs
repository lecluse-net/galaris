import { test, expect } from '@playwright/test'

test('real IDE observes agent writes and preserves native dirty-buffer save conflicts', async ({ page, request }) => {
  const before = await (await request.get('/test/metrics')).json()
  const openingAt = Date.now()
  const opened = await request.post('/test/open')
  expect(opened.ok()).toBeTruthy()
  const { url, session } = await opened.json()
  await page.goto(url)
  await expect(page.locator('.monaco-workbench')).toBeVisible()
  const openingMs = Date.now() - openingAt
  // Git requests explicitly surface native trust management, without granting trust.
  await request.post(`/sessions/${session}/navigate`, { data: { view: 'changes' } })
  await expect(page.getByRole('button', { name: 'Trust', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Trust', exact: true }).click()
  await page.keyboard.press('Escape')
  await request.post('/test/write', { data: { text: 'synthetic unstaged diff\n' } })
  await request.post(`/sessions/${session}/navigate`, { data: { view: 'changes', file: 'source.txt' } })
  await expect(page.locator('.monaco-diff-editor')).toBeVisible()
  await expect(page.locator('.monaco-diff-editor')).toContainText('synthetic agent version')
  await expect(page.locator('.monaco-diff-editor')).toContainText('synthetic unstaged diff')
  await request.post(`/sessions/${session}/navigate`, { data: { view: 'changes' } })
  await expect(page.getByRole('tab', { name: /Git: Changes/ })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('main')).toContainText('synthetic unstaged diff')
  expect((await request.post('/test/stage')).ok()).toBeTruthy()
  await request.post(`/sessions/${session}/navigate`, { data: { view: 'changes' } })
  await expect(page.getByRole('tab', { name: /Staged Changes/ })).toBeVisible()
  await expect(page.getByRole('main')).toContainText('synthetic unstaged diff')
  await request.post('/test/write', { data: { text: 'synthetic agent version\n' } })
  await request.post(`/sessions/${session}/navigate`, { data: { view: 'files', file: 'source.txt' } })
  await page.getByRole('tab', { name: /^Explorer/ }).click()
  await page.getByRole('treeitem', { name: 'source.txt', exact: true }).dblclick()
  const input = page.getByRole('textbox', { name: 'source.txt', exact: true })
  const editor = page.locator('.monaco-editor').filter({ has: input })
  const lines = editor.locator('.view-lines')
  await expect(lines).toContainText('synthetic agent version')
  const changedAt = Date.now()
  await request.post('/test/write', { data: { text: 'synthetic external clean update\n' } })
  await expect(lines).toContainText('synthetic external clean update')
  await test.info().attach('external-change-observation', { body: JSON.stringify({ elapsedMs: Date.now() - changedAt }), contentType: 'application/json' })
  await input.focus()
  await page.keyboard.press('Control+a')
  await page.keyboard.type('synthetic unsaved human version')
  await expect(lines).toContainText('synthetic unsaved human version')
  await request.post('/test/write', { data: { text: 'synthetic conflicting agent update\n' } })
  await expect(lines).toContainText('synthetic unsaved human version')
  await page.keyboard.press('Control+s')
  await expect(page.getByText(/Failed to save.*source.txt|content.*newer/i).first()).toBeVisible()
  expect((await (await request.get('/test/status')).json()).text).toBe('synthetic conflicting agent update\n')
  const after = await (await request.get('/test/metrics')).json()
  await test.info().attach('runtime-footprint', { body: JSON.stringify({ openingMs, before, after }), contentType: 'application/json' })
})
