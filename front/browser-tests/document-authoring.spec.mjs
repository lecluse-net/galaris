import { test, expect, mount, editorHtml } from './fixtures.mjs'

for (const width of [1440, 390]) {
  test(`checklists retain checked state after editing, reopening and export (${width}px)`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: 1000 })
    await page.addInitScript(() => { window.print = () => { window.printCalls = 1 } })
    await mount(page, 'core/util/components/RichTextEditor.vue', { props: { profile: 'document', modelValue: '<p>Review draft</p>' } })
    const editor = page.locator('[data-editor-surface]')
    await editor.locator('p').click()
    await page.getByRole('button', { name: 'Checklist', exact: true }).click()
    const checkbox = editor.getByRole('checkbox', { name: 'Review draft', exact: true })
    await checkbox.check()
    await expect(checkbox).toBeChecked()
    await page.getByRole('button', { name: 'Undo', exact: true }).click()
    await expect(checkbox).not.toBeChecked()
    await page.getByRole('button', { name: 'Redo', exact: true }).click()
    await expect(checkbox).toBeChecked()
    await editor.locator('p').click()
    await page.keyboard.press('End')
    await page.keyboard.press('Enter')
    await page.keyboard.type('Send review')
    await expect(editor.getByRole('checkbox', { name: 'Send review', exact: true })).not.toBeChecked()
    await page.keyboard.press('Tab')
    await expect(editor.locator('.galaris-checklist .galaris-checklist').getByRole('checkbox', { name: 'Send review', exact: true })).toBeVisible()
    await page.keyboard.press('Shift+Tab')
    await expect(editor.locator('.galaris-checklist .galaris-checklist')).toHaveCount(0)
    const saved = await editorHtml(page)
    expect(saved).toContain('data-checked="true"')
    expect(saved).not.toContain('<input')
    await page.evaluate(content => window.testApp.mount({ component: 'core/util/components/RichTextEditor.vue', props: { profile: 'document', modelValue: content } }), saved)
    await expect(checkbox).toBeChecked()
    await checkbox.focus()
    await page.keyboard.press('Space')
    await expect(checkbox).not.toBeChecked()
    await checkbox.check()
    // Printing is a desktop command; mobile uses the PDF share action.
    if (width < 1024) await page.setViewportSize({ width: 1440, height: 1000 })
    await page.getByRole('button', { name: 'Print', exact: true }).click()
    await expect.poll(() => page.evaluate(() => document.querySelector('.document-print-frame')?.contentWindow?.printCalls)).toBe(1)
    const printed = await page.locator('.document-print-frame').getAttribute('srcdoc')
    expect(printed).toContain('data-checked="true"')
    await page.setViewportSize({ width, height: 1000 })
    await page.evaluate(() => window.testApp.setProps({ readonly: true }))
    await expect(checkbox).toBeDisabled()
    await page.screenshot({ path: testInfo.outputPath('checklist.png') })
    await page.evaluate(content => window.testApp.mount({ component: 'core/util/components/RichText.vue', props: { profile: 'document', content } }), saved)
    await expect(page.locator('.galaris-checklist > li[data-checked="true"]')).toContainText('Review draft')
    await expect(page.locator('.galaris-checklist > li[data-checked="false"]')).toContainText('Send review')
  })

  test(`outline follows heading hierarchy and edits without changing content (${width}px)`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: 1000 })
    await mount(page, 'core/util/components/RichTextEditor.vue', { props: { profile: 'document', modelValue: '<h1>Report</h1><h3>Evidence</h3><p>Preserved paragraph</p><h2>Conclusion</h2>' } })
    await page.getByRole('button', { name: 'Document outline', exact: true }).click()
    const outline = page.getByRole('navigation', { name: 'Document outline' })
    await expect(outline.getByText('Report', { exact: true })).toBeVisible()
    // Titles remain directly reachable; the former tree folding is intentionally retired.
    await expect(outline.getByRole('link')).toHaveText(['Report', 'Evidence', 'Conclusion'])
    await outline.getByRole('link', { name: 'Conclusion', exact: true }).focus()
    await page.keyboard.press('Enter')
    await expect(page.locator('[data-editor-surface]')).toBeFocused()
    await page.keyboard.press('End')
    await page.keyboard.type(' updated')
    await expect(outline.getByText('Conclusion updated', { exact: true })).toBeVisible()
    await expect(page.locator('[data-editor-surface] p')).toHaveText('Preserved paragraph')
    const saved = await editorHtml(page)
    await outline.getByRole('button', { name: 'Hide outline', exact: true }).click()
    await expect(outline).toBeHidden()
    await page.getByRole('button', { name: 'Document outline', exact: true }).click()
    expect(await editorHtml(page)).toBe(saved)
    await page.screenshot({ path: testInfo.outputPath('outline.png') })
    await page.evaluate(() => window.testApp.setProps({ modelValue: '<p>No headings yet</p>', readonly: true }))
    await expect(outline.getByText('Add headings to build the outline.')).toBeVisible()
    await expect(outline.getByRole('link')).toHaveCount(0)
  })
}
