test('keyboard links preserve the selection and opening, search and fullscreen remain usable', async ({ page }) => {
  await page.addInitScript(() => { window.open = uri => { window.keyboardOpenedUri = uri; return null } })
  const editor = await documentEditor(page)
  await page.keyboard.press('Control+a')
  await page.keyboard.press('Control+k')
  const link = page.getByRole('dialog', { name: 'Insert or edit link', exact: true })
  await expect(link.getByLabel('Link text', { exact: true })).toHaveValue('Keyboard document')
  await link.getByLabel('URL or Galaris reference', { exact: true }).fill('https://example.invalid/keyboard')
  await link.getByRole('button', { name: 'Apply', exact: true }).click()
  await expect(editor.locator('a')).toHaveText('Keyboard document')
  await page.keyboard.press('Control+Home')
  await page.keyboard.press('Alt+Enter')
  await expect.poll(() => page.evaluate(() => window.keyboardOpenedUri)).toBe('https://example.invalid/keyboard')
  await editor.click()
  await page.keyboard.press('Control+f')
  await expect(page.getByRole('dialog', { name: 'Find', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await editor.click()
  await page.keyboard.press('Control+Shift+j')
  await expect.poll(() => page.locator('.tiptap-galaris-editor').evaluate(element => {
    const rect = element.getBoundingClientRect()
    return rect.width === window.innerWidth && rect.height === window.innerHeight
  })).toBe(true)
  await page.keyboard.press('Escape')
  await expect.poll(() => page.locator('.tiptap-galaris-editor').evaluate(element => element.getBoundingClientRect().height < window.innerHeight)).toBe(true)
})

test('keyboard navigation, line breaks and context focus keep their documented effects', async ({ page }) => {
  const editor = await documentEditor(page)
  await page.keyboard.press('End')
  await page.keyboard.press('Shift+Enter')
  await page.keyboard.type('Last line')
  await expect(editor.locator('p br')).toHaveCount(1)
  await page.keyboard.press('Control+Home')
  await page.keyboard.press('Control+Shift+End')
  expect(await page.evaluate(() => window.getSelection().toString())).toBe('Keyboard document\nLast line')
  await page.keyboard.press('Control+End')
  await page.keyboard.press('Control+Shift+Home')
  expect(await page.evaluate(() => window.getSelection().toString())).toBe('Keyboard document\nLast line')
  await documentEditor(page, '<pre><code class="language-javascript">const answer = 42;</code></pre>')
  await editor.locator('pre code').click()
  await page.keyboard.press('Shift+F10')
  const context = page.getByRole('menu', { name: 'Code block options', exact: true })
  await expect(context.getByRole('menuitem', { name: 'Block language', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(editor).toBeFocused()
  await page.keyboard.press('Control+Home')
  await page.keyboard.press('Alt+Enter')
  await page.keyboard.type('Before code')
  await expect(editor.locator('p').first()).toHaveText('Before code')
  await expect(editor.locator('pre code')).toHaveText('const answer = 42;')
})

