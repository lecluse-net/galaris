test('shortcut help opens from the desktop toolbar or keyboard and restores editing', async ({ page, browserName }, testInfo) => {
  const editor = await documentEditor(page)
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 844 })
    if (width >= 1024) await page.getByRole('button', { name: 'Keyboard help', exact: true }).filter({ visible: true }).click()
    else {
      await editor.click()
      await page.keyboard.press('F1')
    }
    const help = page.getByRole('dialog', { name: 'Keyboard help' })
    await expect(help).toBeVisible()
    await expect(help).toContainText('Heading 6')
    await expect(help).toContainText('Normal text')
    await expect(help.getByRole('row').filter({ hasText: 'Heading 2' }).getByRole('cell').last()).toHaveText((browserName === 'webkit' ? 'Cmd' : 'Ctrl') + '+Alt+2')
    await help.getByRole('row').last().scrollIntoViewIfNeeded()
    await expect(help.getByRole('row').last()).toBeInViewport()
    expect(await help.locator('.galaris-dialog-body').evaluate(element => element.scrollTop)).toBeGreaterThan(0)
    await page.screenshot({ animations: 'disabled', path: testInfo.outputPath(`help-scrolled-${width}.png`) })
    expect(await help.locator('.galaris-dialog-title').evaluate(element => {
      const bounds = element.getBoundingClientRect()
      return element.contains(document.elementFromPoint(bounds.x + bounds.width / 2, bounds.bottom - 2))
    })).toBe(true)
    await page.keyboard.press('Escape')
    await expect(help).toBeHidden()
  }
  await editor.click()
  await page.keyboard.press('Control+Alt+Digit3')
  await expect(editor.locator('h3')).toHaveText('Keyboard document')
})

