for (const width of [1440, 390]) test(`outside clicks dismiss right-click menus across anchors, stopped events and frames (${width}px)`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 })
  await mount(page, 'test-support/browser/ContextMenuHarness.vue')
  const source = page.locator('.menu-row p').first()
  const menu = page.getByRole('menu', { name: 'first', exact: true })
  const open = async () => { await source.click({ button: 'right', position: { x: 5, y: 5 } }); await expect(menu).toBeVisible() }
  await open()
  await source.click({ position: { x: 5, y: 5 } })
  await expect(menu).toBeHidden()
  await open()
  await page.getByRole('button', { name: 'Outside action', exact: true }).click()
  await expect(menu).toBeHidden()
  await expect(page.getByRole('status')).toHaveText('1')
  await open()
  const input = page.getByRole('textbox', { name: 'Outside input' })
  await input.click()
  await expect(menu).toBeHidden()
  await expect(input).toBeFocused()
  await page.keyboard.type('Outside click preserved')
  await expect(input).toHaveValue('Outside click preserved')
  await open()
  const frameAction = page.frameLocator('iframe').getByRole('button', { name: 'Frame action', exact: true })
  await frameAction.click()
  await expect(menu).toBeHidden()
  await expect(page.frameLocator('iframe').getByRole('button', { name: 'Frame clicked', exact: true })).toBeVisible()
  await source.click({ button: 'right', position: { x: 5, y: 5 } })
  await expect(menu).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(menu).toBeHidden()
})

for (const width of [1440, 390]) test(`submenus open on hover, keep their branch and switch siblings (${width}px)`, async ({ page }, testInfo) => {
  await page.setViewportSize({ width, height: 900 })
  await mount(page, 'test-support/browser/ContextSubmenuHarness.vue')
  await page.getByRole('button', { name: 'Actions', exact: true }).click()
  const first = page.getByRole('menuitem', { name: 'First', exact: true })
  await first.hover()
  await expect(page.getByRole('menu', { name: 'First options', exact: true })).toBeInViewport()
  await expect(first).toHaveAttribute('aria-expanded', 'true')
  await page.getByRole('menuitem', { name: 'Nested', exact: true }).hover()
  const nested = page.getByRole('menu', { name: 'Nested options', exact: true })
  await expect(nested).toBeInViewport()
  await nested.getByRole('menuitem', { name: 'Apply', exact: true }).hover()
  await expect(page.getByRole('menu', { name: 'First options', exact: true })).toBeVisible()
  await expect(page.getByRole('status')).toHaveText('0')
  await page.screenshot({ path: testInfo.outputPath('nested-hover.png'), animations: 'disabled' })
  await page.getByRole('menuitem', { name: 'Second', exact: true }).hover()
  await expect(page.getByRole('menu', { name: 'Second options', exact: true })).toBeVisible()
  await expect(nested).toBeHidden()
  await expect(page.getByRole('menu', { name: 'First options', exact: true })).toBeHidden()
  await page.getByRole('menuitem', { name: 'Leaf', exact: true }).hover()
  await expect(page.getByRole('menu', { name: 'Second options', exact: true })).toBeHidden()
  await first.focus()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('menu', { name: 'First options', exact: true })).toBeVisible()
  await expect(page.getByRole('menuitem', { name: 'Nested', exact: true })).toBeFocused()
  await page.keyboard.press('ArrowLeft')
  await expect(page.getByRole('menu', { name: 'First options', exact: true })).toBeHidden()
  await expect(first).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('menu', { name: 'First options', exact: true })).toBeVisible()
  await expect(page.getByRole('menuitem', { name: 'Nested', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('menu', { name: 'Root', exact: true })).toBeVisible()
  await expect(first).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('menu')).toHaveCount(0)
})

test.describe('touch submenus', () => {
  test.use({ hasTouch: true, viewport: { width: 390, height: 900 } })
  test('an outside tap dismisses the menu and activates the tapped control', async ({ page }) => {
    await mount(page, 'test-support/browser/ContextMenuHarness.vue')
    await page.getByRole('region', { name: 'first', exact: true }).click({ button: 'right' })
    await expect(page.getByRole('menu', { name: 'first', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Outside action', exact: true }).tap()
    await expect(page.getByRole('menu')).toHaveCount(0)
    await expect(page.getByRole('status')).toHaveText('1')
  })
  test('tapping keeps submenu actions usable and disabled items inert', async ({ page }) => {
    await mount(page, 'test-support/browser/ContextSubmenuHarness.vue', { props: { disabled: true } })
    await page.getByRole('button', { name: 'Actions', exact: true }).tap()
    const first = page.getByRole('menuitem', { name: 'First', exact: true })
    await first.dispatchEvent('pointerenter', { pointerType: 'touch' })
    await expect(first).toHaveAttribute('aria-expanded', 'false')
    await page.evaluate(() => window.testApp.setProps({ disabled: false }))
    await first.tap()
    await page.getByRole('menuitem', { name: 'Nested', exact: true }).tap()
    await page.getByRole('menuitem', { name: 'Apply', exact: true }).tap()
    await expect(page.getByRole('status')).toHaveText('1')
    await expect(page.getByRole('menu')).toHaveCount(0)
  })
})

for (const width of [1440, 390]) test(`context menus support pointer, keyboard and state changes without an action button (${width}px)`, async ({ page }, testInfo) => {
  await page.setViewportSize({ width, height: 900 })
  await mount(page, 'test-support/browser/ContextMenuHarness.vue')
  const first = page.getByRole('region', { name: 'first', exact: true })
  const second = page.getByRole('region', { name: 'second', exact: true })
  await expect(first.getByRole('button')).toHaveCount(0)
  await first.click({ button: 'right' })
  await expect(page.getByRole('menu', { name: 'first' })).toBeVisible()
  await second.click({ button: 'right' })
  await expect(page.getByRole('menu', { name: 'first' })).toBeHidden()
  await page.getByRole('menuitem', { name: 'Apply', exact: true }).click()
  await expect(page.getByRole('menu')).toHaveCount(0)
  await expect(second.locator('span').last()).toHaveText('1')
  await first.focus()
  await expect(first).toBeFocused()
  await page.keyboard.press('Shift+F10')
  await expect(page.getByRole('menu', { name: 'first' })).toBeVisible()
  await page.evaluate(() => window.testApp.setProps({ disabled: true }))
  await expect(page.getByRole('menuitem', { name: 'Apply' })).toHaveAttribute('aria-disabled', 'true')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('menu')).toHaveCount(0)
  await expect(first).toBeFocused()
  await page.evaluate(() => window.testApp.setProps({ disabled: false, fail: true }))
  await first.click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Apply' }).click()
  await expect(page.getByText('Synthetic failure', { exact: true })).toBeVisible()
  await expect(first.locator('span').last()).toHaveText('0')
  await page.evaluate(() => window.testApp.setProps({ fail: false }))
  await first.click({ button: 'right' })
  await expect(page.getByRole('menu', { name: 'first' })).toBeVisible()
  await expect(page.getByRole('menuitem', { name: 'Apply', exact: true })).toBeFocused()
  await expect(page.getByRole('menu', { name: 'first' })).toBeInViewport()
  await page.screenshot({ path: testInfo.outputPath('context-menu.png'), animations: 'disabled' })
  await page.mouse.click(width - 2, 890)
  await expect(page.getByRole('menu')).toHaveCount(0)
})

test('selected message text keeps its native context menu', async ({ page }) => {
  await mount(page, 'test-support/browser/ContextMenuHarness.vue', { props: { preserveSelection: true } })
  const text = page.locator('.menu-row p').first()
  await text.evaluate(element => {
    const range = document.createRange(); range.selectNodeContents(element)
    const selection = window.getSelection(); selection.removeAllRanges(); selection.addRange(range)
  })
  await text.click({ button: 'right' })
  await expect(page.getByRole('menu')).toHaveCount(0)
  await expect.poll(() => page.evaluate(() => window.getSelection().toString())).toContain('selectable text')
})

test('document menus reuse row actions and respect read-only and deletion protection', async ({ page }) => {
  const entry = { item: { ...document, read_only: false, source_managed: false, deletion_protected: true, access: { can_read: true, can_write: true } }, owner_label: 'Synthetic owner', children_count: 0 }
  await jsonRoute(page, '**/api/documents/doc-a', { ...document, media_type: 'text/html', payload: { text: '<p>Synthetic document</p>' } })
  await mount(page, 'app/document/components/DocumentLibraryDocument.vue', { props: {
    entry, selectedDocumentId: null, busy: false, children: {}, loading: {}, errors: {}, expanded: [], dropTarget: null, dropPlacement: '',
  } })
  const row = page.locator('.document-branch-row')
  await row.click({ button: 'right' })
  await expect(page.getByRole('menuitem', { name: 'Delete', exact: true })).toHaveCount(0)
  await page.getByRole('menuitem', { name: 'Rename', exact: true }).click()
  await expect.poll(() => page.evaluate(() => window.testApp.events.filter(event => event.name === 'action').map(event => event.args[1]))).toEqual(['rename'])
  await page.evaluate(entry => window.testApp.setProps({ entry }), { ...entry, item: { ...entry.item, read_only: true } })
  await row.click({ button: 'right' })
  await expect(page.getByRole('menuitem', { name: 'Rename', exact: true })).toHaveCount(0)
  await page.getByRole('menuitem', { name: 'Open', exact: true }).click()
  await expect.poll(() => page.evaluate(() => window.testApp.events.filter(event => event.name === 'select').length)).toBe(1)
})

