import { test, expect, mount, jsonRoute } from './fixtures.mjs'

const entry = (uri, name, is_collection = false) => ({ uri, name, is_collection, media_type: is_collection ? '' : 'text/plain', size: 10, capabilities: is_collection ? ['list'] : ['read', 'info'] })
const listing = entries => ({ entries, next_cursor: null, truncated: false })
const audio = Buffer.alloc(46)
audio.write('RIFF'); audio.writeUInt32LE(38, 4); audio.write('WAVEfmt ', 8)
audio.writeUInt32LE(16, 16); audio.writeUInt16LE(1, 20); audio.writeUInt16LE(1, 22)
audio.writeUInt32LE(8000, 24); audio.writeUInt32LE(16000, 28)
audio.writeUInt16LE(2, 32); audio.writeUInt16LE(16, 34); audio.write('data', 36); audio.writeUInt32LE(2, 40)

for (const width of [1440, 390]) test(`internal file picker keeps multiple selections across folders and search at ${width}px`, async ({ page }, testInfo) => {
  await page.setViewportSize({ width, height: 900 })
  await jsonRoute(page, '**/api/file-share/browser/schemes?*', [{ scheme: 'file', label: 'Managed files', capabilities: ['list'], native: true }])
  await page.route('**/api/file-share/browser/thumbnail?*', route => route.fulfill({ status: 404 }))
  await page.route('**/api/file-share/browser/content?*', route => {
    const uri = new URL(route.request().url()).searchParams.get('uri')
    expect(new URL(route.request().url()).searchParams.get('management')).toBe('true')
    expect(['file://one', 'file://audio']).toContain(uri)
    return route.fulfill(uri === 'file://audio' ? { contentType: 'audio/wav', body: audio } : { contentType: 'text/plain', body: 'Synthetic preview content' })
  })
  await page.route('**/api/file-share/browser/entries?*', route => {
    const uri = new URL(route.request().url()).searchParams.get('uri')
    return route.fulfill({ json: listing(uri === 'file://' ? [entry('file://folder/', 'Synthetic folder', true), entry('file://one', 'One.txt'), { ...entry('file://audio', 'Synthetic audio.wav'), media_type: 'audio/wav' }] : [entry('file://two', 'Two.txt'), entry('file://three', 'Three.txt')]) })
  })
  await page.route('**/api/file-share/browser/search?*', route => {
    expect(new URL(route.request().url()).searchParams.get('query')).toBe('Search')
    return route.fulfill({ json: { hits: [{ resource: entry('file://search', 'Search.txt') }], truncated: false, next_cursor: null } })
  })
  await mount(page, 'resourcePicker.vue', { route: '/chat', browserHistory: true, props: { modelValue: true, agentId: 7 } })
  if (width < 1024) await page.getByRole('button', { name: 'Show locations', exact: true }).click()
  await page.locator('.file-scheme-label').filter({ hasText: /^Managed files$/ }).click()
  const main = page.locator('.file-main')
  await main.getByRole('button', { name: 'Select One.txt', exact: true }).click()
  await main.getByRole('button', { name: 'Preview One.txt', exact: true }).click()
  const preview = page.getByRole('dialog', { name: 'Open preview of One.txt', exact: true })
  await expect(preview).toContainText('Synthetic preview content')
  await page.screenshot({ path: testInfo.outputPath('internal-picker-preview.png'), fullPage: true })
  await page.keyboard.press('Escape')
  await expect(preview).toHaveCount(0)
  await expect(main.getByRole('checkbox', { name: 'Select One.txt', exact: true })).toBeChecked()
  await main.getByRole('button', { name: 'Preview Synthetic audio.wav', exact: true }).click()
  const audioPreview = page.getByRole('dialog', { name: 'Synthetic audio.wav', exact: true })
  await expect(audioPreview.locator('audio')).toHaveAttribute('src', /^blob:/)
  await page.keyboard.press('Escape')
  await expect(audioPreview).toHaveCount(0)
  await expect(main.getByRole('checkbox', { name: 'Select Synthetic audio.wav', exact: true })).not.toBeChecked()
  const folder = main.getByRole('checkbox', { name: 'Select Synthetic folder', exact: true })
  await folder.check()
  await expect(folder).toBeChecked()
  await folder.uncheck()
  await folder.focus()
  await page.keyboard.press('Space')
  await expect(folder).toBeChecked()
  await main.getByRole('button', { name: 'Open Synthetic folder', exact: true }).click()
  await main.getByRole('button', { name: 'Select Two.txt', exact: true }).click()
  await main.getByRole('button', { name: 'Select Three.txt', exact: true }).click({ modifiers: ['Shift'] })
  await expect(page.getByText('4 item(s) selected', { exact: true })).toBeVisible()
  await page.getByRole('textbox', { name: 'Search this location', exact: true }).fill('Search')
  await main.getByRole('button', { name: 'Select Search.txt', exact: true }).click()
  await expect(page.getByText('5 item(s) selected', { exact: true })).toBeVisible()
  await page.getByRole('textbox', { name: 'Search this location', exact: true }).fill('')
  await main.getByRole('navigation', { name: 'File navigation', exact: true }).getByRole('button', { name: 'file://', exact: true }).click()
  await expect(folder).toBeChecked()
  await page.screenshot({ path: testInfo.outputPath('internal-picker.png'), fullPage: true })
  await page.getByRole('button', { name: 'Select', exact: true }).click()
  const selected = await page.evaluate(() => window.testApp.events.filter(event => event.name === 'select').at(-1).args)
  expect(selected[0].map(value => value.uri)).toEqual(['file://one', 'file://folder/', 'file://two', 'file://three', 'file://search'])
  expect(selected[1]).toBe(7)
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page).toHaveURL(/\/chat$/)
})
