import { selectDocumentContext, test, expect, mount } from './fixtures.mjs'

const source = 'const greeting = "Bonjour";\nconsole.log(greeting, 42);'
const content = `<p>Before</p><pre><code class="language-javascript">${source}</code></pre><pre><code class="language-python">print("untouched")</code></pre><p>After</p>`
const saved = page => page.evaluate(() => window.testApp.events.filter(event => event.name === 'update:modelValue').at(-1)?.value)
const menu = page => page.getByRole('toolbar', { name: 'Contextual actions', exact: true })

test('context menu commands change the targeted block, keep its text and undo without inserting blocks', async ({ page }, testInfo) => {
  await mount(page, 'core/util/components/RichTextEditor.vue', { props: { profile: 'document', modelValue: content } })
  const blocks = page.locator('[data-editor-surface] pre code')
  await expect(menu(page)).toBeHidden()
  await selectDocumentContext(page, blocks.first().locator('.hljs-keyword').first())
  await expect(menu(page)).toBeVisible()
  await menu(page).getByRole('button', { name: 'Block language', exact: true }).click()
  await page.getByRole('menuitemradio', { name: 'TypeScript', exact: true }).click()
  await expect(page.getByRole('menu', { name: 'Block language', exact: true })).toBeHidden()
  await expect(blocks).toHaveCount(2)
  await expect(blocks.first()).toHaveClass('language-typescript')
  await expect(blocks.nth(1)).toHaveClass('language-python')
  expect(await blocks.first().innerText()).toBe(source)
  await expect.poll(() => saved(page)).toContain('language-typescript')
  await expect(page.locator('[data-editor-surface]')).toBeFocused()
  await page.keyboard.press('Control+z')
  await expect(blocks.first()).toHaveClass('language-javascript')
  await selectDocumentContext(page, blocks.first().locator('.hljs-keyword').first())
  await menu(page).getByRole('button', { name: 'Line numbers', exact: true }).click()
  await expect(blocks.first()).toHaveAttribute('data-code-lines', 'true')
  await expect(blocks.first().locator('.galaris-code-line')).toHaveCount(2)
  expect(await blocks.first().innerText()).toBe(source)
  await selectDocumentContext(page, blocks.first().locator('.hljs-keyword').first())
  await menu(page).getByRole('button', { name: 'Wrap lines', exact: true }).click()
  await expect(blocks.first()).toHaveAttribute('data-code-nowrap', 'true')
  await expect(blocks.first()).toHaveCSS('white-space', 'pre')
  const html = await saved(page)
  expect(html).toContain('data-code-lines="true"')
  expect(html).not.toMatch(/galaris-code-line|codeLine:|hljs-/)
  await page.screenshot({ path: testInfo.outputPath('context-code-tools.png') })
  await page.evaluate(() => window.testApp.setProps({ modelValue: '<p>Another document</p>' }))
  await page.evaluate(value => window.testApp.setProps({ modelValue: value }), html)
  await expect(blocks.first()).toHaveAttribute('data-code-lines', 'true')
  await expect(blocks.first()).toHaveAttribute('data-code-nowrap', 'true')
  await expect(blocks.first().locator('.galaris-code-line')).toHaveCount(2)
  await blocks.first().locator('.hljs-keyword').first().click()
  await page.keyboard.press('End')
  await page.keyboard.press('Enter')
  await page.keyboard.insertText('// new line')
  await expect(blocks.first().locator('.galaris-code-line')).toHaveCount(3)
  expect(await saved(page)).not.toMatch(/galaris-code-line|codeLine:/)
  await page.locator('[data-editor-surface] p').last().click()
  await expect(menu(page)).toBeHidden()
})

test('copy excludes numbers and copying failures are visible; read-only mode protects authored options', async ({ page }, testInfo) => {
  await page.addInitScript(() => Object.defineProperty(navigator, 'clipboard', { value: { writeText: async value => { window.copiedCode = value } } }))
  await mount(page, 'core/util/components/RichTextEditor.vue', { props: { profile: 'document', modelValue: content.replace('<code ', '<code data-code-lines="true" ') } })
  const block = page.locator('[data-editor-surface] pre code').first()
  await selectDocumentContext(page, block.locator('.hljs-keyword').first())
  await menu(page).getByRole('button', { name: 'Copy code', exact: true }).click()
  expect(await page.evaluate(() => window.copiedCode)).toBe(source)
  await expect(page.getByText('Code copied', { exact: true })).toBeVisible()
  expect(await saved(page)).toBeUndefined()
  await expect(page.locator('[data-editor-surface] pre .galaris-code-actions button')).toHaveCount(0)
  await page.evaluate(() => window.testApp.setProps({ readonly: true }))
  const headerCopy = page.locator('[data-editor-surface] pre').nth(1).getByRole('button', { name: 'Copy code', exact: true })
  await expect(headerCopy).toBeVisible()
  await headerCopy.focus()
  await page.keyboard.press('Enter')
  await expect.poll(() => page.evaluate(() => window.copiedCode)).toBe('print("untouched")')
  expect(await saved(page)).toBeUndefined()
  await expect(menu(page)).toBeHidden()
  await page.evaluate(() => { navigator.clipboard.writeText = async () => { throw new Error('denied') } })
  await headerCopy.click()
  await expect(page.getByText('Unable to copy the code. Please try again.', { exact: true })).toBeVisible()
  await page.evaluate(content => window.testApp.mount({ component: 'core/util/components/RichTextEditor.vue', props: { profile: 'document', modelValue: content, readonly: true } }), content)
  await page.evaluate(() => { navigator.clipboard.writeText = async value => { window.copiedCode = value } })
  await page.locator('[data-editor-surface] pre').nth(1).getByRole('button', { name: 'Copy code', exact: true }).click()
  expect(await page.evaluate(() => window.copiedCode)).toBe('print("untouched")')
  await page.screenshot({ path: testInfo.outputPath('readonly-code-copy.png') })
  await page.evaluate(() => window.testApp.setProps({ readonly: false }))
  await expect(page.locator('[data-editor-surface] pre .galaris-code-actions button')).toHaveCount(0)
  await page.evaluate(() => window.testApp.setProps({ readonly: true }))
  await page.locator('[data-editor-surface] pre').first().getByRole('button', { name: 'Copy code', exact: true }).click()
  await expect.poll(() => page.evaluate(() => window.copiedCode)).toBe(source)
  expect(await saved(page)).toBeUndefined()

  await page.evaluate(content => window.testApp.mount({ component: 'core/util/components/RichText.vue', dark: true, props: { profile: 'document', content } }), content.replace('<code ', '<code data-code-lines="true" '))
  await page.evaluate(() => window.testApp.dark(true))
  const readerCopy = page.locator('.rich-content pre').first().getByRole('button', { name: 'Copy code', exact: true })
  await readerCopy.click()
  await expect.poll(() => page.evaluate(() => window.copiedCode)).toBe(source)
  await page.screenshot({ path: testInfo.outputPath('reader-code-copy.png') })
  await page.evaluate(() => { navigator.clipboard.writeText = async () => { throw new Error('denied') } })
  await readerCopy.click()
  await expect(page.getByText('Unable to copy the code. Please try again.', { exact: true })).toBeVisible()
  await page.evaluate(() => {
    navigator.clipboard.writeText = async value => { window.copiedCode = value }
    window.testApp.setProps({ content: '<pre><code class="language-html">  &lt;b&gt;literal&lt;/b&gt;\n</code></pre>' })
  })
  await expect(page.locator('.rich-content pre .galaris-code-actions button')).toHaveCount(1)
  await readerCopy.click()
  await expect.poll(() => page.evaluate(() => window.copiedCode)).toBe('  <b>literal</b>\n')
})

test('line gutters follow wrapped lines in editing, reading and print without entering the text', async ({ page }) => {
  await page.addInitScript(() => { window.print = () => {} })
  await page.setViewportSize({ width: 390, height: 844 })
  const code = '  // ' + 'long text '.repeat(30) + '\nconst value = 42;\n'
  const html = `<pre><code class="language-javascript" data-code-lines="true">${code}</code></pre>`
  await mount(page, 'core/util/components/RichTextEditor.vue', { dark: true, props: { profile: 'document', modelValue: html } })
  const block = page.locator('[data-editor-surface] pre code')
  const numbers = block.locator('.galaris-code-line')
  await expect(block).toHaveAttribute('data-code-lines', 'true')
  await expect(numbers).toHaveCount(3)
  expect((await numbers.nth(1).boundingBox()).y - (await numbers.first().boundingBox()).y).toBeGreaterThan(18)
  await block.locator('.hljs-keyword').click()
  await menu(page).getByRole('button', { name: 'Block language', exact: true }).focus()
  await expect(menu(page).getByRole('button', { name: 'Block language', exact: true })).toBeFocused()
  await block.locator('.hljs-keyword').click()
  // Printing belongs to the desktop toolbar; mobile exposes PDF sharing.
  // Preserve the authored code while moving from the wrapped mobile view.
  const editingText = await block.textContent()
  await page.setViewportSize({ width: 1440, height: 900 })
  expect(await block.textContent()).toBe(editingText)
  await page.getByRole('button', { name: 'Print', exact: true }).click()
  const printed = page.frameLocator('.document-print-frame').locator('pre code')
  await expect(printed.locator('.galaris-code-line')).toHaveCount(3)
  expect(await printed.textContent()).toBe(code)
  await page.evaluate(html => window.testApp.mount({ component: 'core/util/components/RichText.vue', props: { profile: 'document', content: html } }), html)
  const reading = page.locator('.rich-content pre code')
  await expect(reading.locator('.galaris-code-line')).toHaveCount(3)
  expect(await reading.textContent()).toBe(code)
})
