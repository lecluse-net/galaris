import { test, expect, mount, editorHtml } from './fixtures.mjs'

const component = 'core/util/components/RichTextEditor.vue'
const dialog = page => page.getByRole('dialog', { name: 'Equation editor', exact: true })

for (const kind of ['inline', 'block']) for (const width of [1440, 390]) {
  test(`equation context actions preserve surrounding text (${kind}, ${width})`, async ({ page, context }, testInfo) => {
    await context.grantPermissions(['clipboard-read', 'clipboard-write'])
    await page.setViewportSize({ width, height: 1000 })
    const formula = kind === 'inline' ? '<p>Before <span data-math="inline">\\frac{a}{b}</span> after</p>' : '<p>Before</p><p data-math="block">\\frac{a}{b}</p><p>after</p>'
    await mount(page, component, { props: { profile: 'document', modelValue: formula } })
    const editor = page.locator('[data-editor-surface]'), math = editor.locator('[data-math]')
    await expect(math.locator('.ML__latex')).toBeVisible()
    await page.screenshot({ path: testInfo.outputPath('equation-context.png'), fullPage: true })
    await math.click()
    await expect(dialog(page)).toHaveCount(0)
    const keyboardTools = page.getByRole('toolbar', { name: 'Contextual actions', exact: true })
    await keyboardTools.getByRole('button', { name: 'Cut', exact: true }).focus()
    await expect(keyboardTools.getByRole('button', { name: 'Cut', exact: true })).toBeFocused()
    await command(page, kind === 'inline' ? 'Inline equation' : 'Block equation')
    await expect(dialog(page)).toBeVisible()
    await page.keyboard.press('Escape')
    const actions = page.getByRole('toolbar', { name: 'Contextual actions', exact: true })
    const open = async () => {
      await math.click()
      await expect(dialog(page)).toHaveCount(0)
      await expect(actions).toBeVisible()
    }
    const action = name => actions.getByRole('button', { name, exact: true })
    await open()
    if (width >= 1024) await page.keyboard.press('Escape')
    await command(page, kind === 'inline' ? 'Inline equation' : 'Block equation')
    await expect(dialog(page).getByRole('textbox', { name: 'LaTeX source', exact: true })).toHaveValue('\\frac{a}{b}')
    await dialog(page).getByRole('button', { name: 'Cancel', exact: true }).click()
    await open()
    await action('Copy').click()
    expect(await editorHtml(page)).toBe(formula)
    const clipboard = await page.evaluate(async () => {
      const items = await navigator.clipboard.read()
      return (await items.find(item => item.types.includes('text/html')).getType('text/html')).text()
    })
    expect(clipboard).toContain(`data-math="${kind}"`)
    expect(clipboard).toContain('\\frac{a}{b}')
    await open()
    await action(kind === 'inline' ? 'Write before equation' : 'Insert paragraph before block').click()
    await page.keyboard.type('Left ')
    expect(await editorHtml(page)).toContain('Left ')
    await open()
    await action(kind === 'inline' ? 'Write after equation' : 'Insert paragraph after block').click()
    await page.keyboard.type(' Right')
    const saved = await editorHtml(page)
    expect(saved.replaceAll('&nbsp;', ' ')).toBe(kind === 'inline'
      ? '<p>Before Left <span data-math="inline">\\frac{a}{b}</span> Right after</p>'
      : '<p>Before</p><p>Left </p><p data-math="block">\\frac{a}{b}</p><p> Right</p><p>after</p>')
    await open()
    await page.screenshot({ path: testInfo.outputPath('equation-actions.png'), fullPage: true })
    await action('Cut').click()
    await expect(math).toHaveCount(0)
    await page.keyboard.press('Control+z')
    await expect(math).toHaveCount(1)
    expect(await editorHtml(page)).toBe(saved)
    await open()
    await action('Delete equation').click()
    await expect(math).toHaveCount(0)
    await page.keyboard.press('Control+z')
    await expect(math).toHaveCount(1)
    expect(await editorHtml(page)).toBe(saved)
    await page.evaluate(() => window.testApp.setProps({ readonly: true }))
    await math.click({ button: 'right' })
    await expect(actions).toHaveCount(0)
    expect(await editorHtml(page)).toBe(saved)
  })
}
async function command(page, name) {
  const button = page.getByRole('button', { name, exact: true })
  if (!await button.isVisible()) await page.getByRole('button', { name: 'More tools', exact: true }).click()
  await button.click()
}

for (const [profile, width, dark] of [['document', 1440, false], ['document', 390, false], ['rich-text', 1440, false], ['document', 390, true]]) {
  test(`equations remain editable after insertion, undo, reopening and reading (${profile}, ${width}, dark=${dark})`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: 1000 })
    const external = [], failed = []
    page.on('request', request => { if (/^https?:/.test(request.url()) && !request.url().startsWith('http://localhost:8000')) external.push(request.url()) })
    page.on('requestfailed', request => failed.push(request.url()))
    await mount(page, component, { dark, props: { profile, modelValue: '<p>Before after</p>' } })
    const editor = page.locator('[data-editor-surface]')
    await editor.locator('p').click(); await page.keyboard.press('Home'); await page.keyboard.press('ArrowRight')
    await command(page, 'Inline equation')
    await expect(dialog(page).locator('math-field')).toBeVisible()
    await dialog(page).locator('math-field').click()
    await page.keyboard.type('x')
    await expect(dialog(page).getByRole('textbox', { name: 'LaTeX source', exact: true })).toHaveValue('x')
    await dialog(page).locator('.equation-keyboard').getByLabel('7', { exact: true }).filter({ visible: true }).click()
    await expect(dialog(page).getByRole('textbox', { name: 'LaTeX source', exact: true })).toHaveValue('x7')
    await dialog(page).getByRole('textbox', { name: 'LaTeX source', exact: true }).fill('\\frac{a}{b}')
    await page.screenshot({ path: testInfo.outputPath('equation-dialog.png'), fullPage: true })
    await dialog(page).getByRole('button', { name: 'Apply', exact: true }).click()
    await expect(dialog(page)).toHaveCount(0)
    await expect(editor.locator('span[data-math="inline"] .ML__latex')).toBeVisible()
    await editor.locator('[data-math="inline"]').dblclick()
    await expect(dialog(page).getByRole('textbox', { name: 'LaTeX source', exact: true })).toHaveValue('\\frac{a}{b}')
    await dialog(page).getByRole('textbox', { name: 'LaTeX source', exact: true }).fill('x^2')
    await dialog(page).getByRole('button', { name: 'Cancel', exact: true }).click()
    expect(await editorHtml(page)).toContain('\\frac{a}{b}')
    await editor.locator('[data-math="inline"]').dblclick()
    await dialog(page).getByRole('textbox', { name: 'LaTeX source', exact: true }).fill('x^2')
    await dialog(page).getByRole('button', { name: 'Apply', exact: true }).click()
    expect(await editorHtml(page)).toContain('x^2')
    await page.keyboard.press('Control+z')
    expect(await editorHtml(page)).toContain('\\frac{a}{b}')
    await page.keyboard.press('ArrowRight')
    await page.keyboard.press('End')
    await command(page, 'Block equation')
    await dialog(page).getByRole('textbox', { name: 'LaTeX source', exact: true }).fill('\\sqrt{x+1}')
    await dialog(page).getByRole('button', { name: 'Apply', exact: true }).click()
    await expect(editor.locator('p[data-math="block"] .ML__latex')).toBeVisible()
    const saved = await editorHtml(page)
    expect(await editor.evaluate(element => { const copy = element.cloneNode(true); copy.querySelectorAll('[data-math]').forEach(node => node.remove()); return copy.textContent })).toBe('Before after')
    expect(saved).toContain('<p data-math="block">\\sqrt{x+1}</p>')
    expect(saved).not.toContain('ML__')
    await page.evaluate(async ({ profile, modelValue }) => window.testApp.mount({ component: 'core/util/components/RichTextEditor.vue', props: { profile, modelValue } }), { profile, modelValue: saved })
    await expect(editor.locator('[data-math]')).toHaveCount(2)
    expect(await editorHtml(page)).toBe(saved)
    // Keyboard activation and backdrop dismissal leave the saved source untouched.
    await editor.locator('[data-math="inline"]').dblclick()
    await page.locator('.q-dialog__backdrop').last().click({ position: { x: 2, y: 2 } })
    await expect(dialog(page)).toHaveCount(0)
    await page.evaluate(() => { const element = document.querySelector('[data-editor-surface]'); const editor = element.editor; editor.commands.setNodeSelection(2); editor.view.focus() })
    await page.keyboard.press('Enter')
    await expect(dialog(page)).toBeVisible()
    await page.keyboard.press('Escape')
    await page.evaluate(() => window.testApp.setProps({ readonly: true }))
    await editor.locator('[data-math="inline"]').dblclick()
    await expect(dialog(page)).toHaveCount(0)
    await page.evaluate(({ profile, content }) => window.testApp.mount({ component: 'core/util/components/RichText.vue', props: { profile, content } }), { profile, content: saved })
    await expect(page.locator('.rich-content [data-math] .ML__latex')).toHaveCount(2)
    await page.screenshot({ path: testInfo.outputPath('equations-reader.png'), fullPage: true })
    expect(external).toEqual([])
    expect(failed).toEqual([])
  })
}

test('equation drafts cannot write into a changed document and static exports embed fonts', async ({ page, context }, testInfo) => {
  const content = '<p>Inline <span data-math="inline">x^2</span>.</p><p data-math="block">\\frac{1}{2}</p>'
  await mount(page, component, { props: { profile: 'document', modelValue: content } })
  await page.locator('[data-editor-surface] [data-math="inline"]').dblclick()
  await expect(dialog(page).locator('math-field')).toBeVisible()
  await page.evaluate(() => window.testApp.setProps({ modelValue: '<p>Another document</p>' }))
  await expect(dialog(page)).toHaveCount(0)
  expect(await editorHtml(page)).toBe('<p>Another document</p>')
  const snapshot = await page.evaluate(async content => {
    const { preparePortableDocumentSnapshot } = await import('/core/util/documentSnapshot.ts')
    return preparePortableDocumentSnapshot(content, 'Synthetic equations', new AbortController().signal)
  }, content)
  expect(snapshot).toContain('Arno Gourdol')
  expect(snapshot).toContain('Khan Academy')
  const printed = await context.newPage(), requests = []
  printed.on('request', request => requests.push(request.url()))
  await printed.setContent(snapshot)
  await printed.evaluate(async () => { await document.fonts.load('16px KaTeX_Main'); await document.fonts.ready })
  await expect(printed.locator('[data-math] .ML__latex')).toHaveCount(2)
  expect(await printed.evaluate(() => document.fonts.check('16px KaTeX_Main'))).toBeTruthy()
  await printed.pdf({ path: testInfo.outputPath('equations.pdf'), printBackground: true })
  await printed.screenshot({ path: testInfo.outputPath('equations-print.png'), fullPage: true })
  expect(requests.filter(url => /^https?:/.test(url))).toEqual([])
  await printed.close()
})

test('reader keeps prose visible while math loads and rejects a late rendering from previous content', async ({ page }) => {
  let release
  const gate = new Promise(resolve => { release = resolve })
  await page.route('**/core/util/mathliveRuntime.ts*', async route => { await gate; await route.continue() })
  await mount(page, 'core/util/components/RichText.vue', { props: { content: '<p>Visible prose <span data-math="inline">x^2</span></p>' } })
  await expect(page.locator('.rich-content')).toContainText('Visible prose')
  await page.evaluate(() => window.testApp.setProps({ content: '<p>New content</p>' }))
  await expect(page.locator('.rich-content')).toHaveText('New content')
  const loaded = page.waitForResponse(response => response.url().includes('/core/util/mathliveRuntime.ts'))
  release()
  await loaded
  await expect(page.locator('.rich-content')).toHaveText('New content')
  await expect(page.locator('.rich-content [data-math]')).toHaveCount(0)
})
