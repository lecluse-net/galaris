import { test, expect } from '@playwright/test'
import { collectPageErrors } from '../page-errors.mjs'

test.use({ serviceWorkers: 'allow' })

test('folder and document shortcuts create, rename and confirm deletion in the assembled library', async ({ page, request }, testInfo) => {
  test.setTimeout(120_000)
  const errors = collectPageErrors(page)
  const seed = await request.post('/api/__test/seed')
  expect(seed.ok()).toBe(true)
  const credentials = await seed.json()
  await page.goto('/user/login')
  await page.locator('input[type=email]').fill(credentials.email)
  await page.locator('input[type=password]').fill(credentials.password)
  const login = page.waitForResponse(response => response.url().endsWith('/api/auth/login-json'))
  await page.locator('button[type=submit]').click()
  const session = await (await login).json()
  await expect(page.locator('input[type=password]')).toHaveCount(0)
  const headers = { Authorization: `Bearer ${session.access_token}` }
  const response = await request.post('/api/documents/tags', { headers, data: { name: `Synthetic keyboard ${credentials.agent_id}`, parent_id: null } })
  expect(response.ok()).toBe(true)
  const folder = await response.json()
  await errors.settle()
  await page.goto('/documents')
  const heading = page.getByRole('heading', { name: 'Documents', exact: true })
  await heading.click()
  await page.getByText(folder.name, { exact: true }).hover()
  await expect.poll(() => page.getByText(folder.name, { exact: true }).evaluate(element => element.matches(':hover'))).toBe(true)
  await page.keyboard.press('F7')
  const folderName = page.getByRole('textbox', { name: 'Nom', exact: true })
  await expect(folderName).toBeFocused()
  await folderName.fill('Synthetic keyboard child')
  await folderName.press('Enter')
  await expect(folderName).toHaveCount(0)
  await heading.click()
  await page.getByText('Synthetic keyboard child', { exact: true }).hover()
  await page.keyboard.press('F3')
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Titre', { exact: true }).fill('Synthetic shortcut report')
  const creation = page.waitForResponse(response => new URL(response.url()).pathname === '/api/documents' && response.request().method() === 'POST')
  await dialog.getByRole('button', { name: 'Créer', exact: true }).click()
  const created = await creation
  expect(created.ok()).toBe(true)
  const document = await created.json()
  await expect(dialog).toHaveCount(0)
  const title = page.getByLabel('Titre', { exact: true })
  await expect(title).toHaveValue('Synthetic shortcut report')
  const tree = page.getByLabel('Documents du dossier Synthetic keyboard child', { exact: true })
  await expect(tree.getByText('Synthetic shortcut report', { exact: true })).toBeVisible()
  await heading.click()
  await tree.getByText('Synthetic shortcut report', { exact: true }).hover()
  await page.keyboard.press('F2')
  await expect(title).toBeFocused()
  const renamed = page.waitForResponse(response => new URL(response.url()).pathname === `/api/documents/${document.id}` && response.request().method() === 'PATCH')
  await title.fill('Synthetic renamed report')
  await title.press('Tab')
  expect((await renamed).ok()).toBe(true)
  await expect(tree.getByText('Synthetic renamed report', { exact: true })).toBeVisible()
  await heading.click()
  await tree.getByText('Synthetic renamed report', { exact: true }).hover()
  await page.keyboard.press('F7')
  await expect(dialog).toContainText('Nouveau sous-document de Synthetic renamed report')
  await dialog.getByRole('button', { name: 'Annuler', exact: true }).click()
  await heading.click()
  await tree.getByText('Synthetic renamed report', { exact: true }).hover()
  await page.keyboard.press('Delete')
  await expect(dialog).toContainText('Synthetic renamed report')
  await dialog.getByRole('button', { name: 'Annuler', exact: true }).click()
  expect((await request.get(`/api/documents/${document.id}`, { headers })).ok()).toBe(true)
  await heading.click()
  await tree.getByText('Synthetic renamed report', { exact: true }).hover()
  await page.keyboard.press('Delete')
  const deleted = page.waitForResponse(response => new URL(response.url()).pathname === `/api/documents/${document.id}` && response.request().method() === 'DELETE')
  await dialog.getByRole('button', { name: 'Supprimer le document', exact: true }).click()
  expect((await deleted).ok()).toBe(true)
  await expect(tree.getByText('Synthetic renamed report', { exact: true })).toHaveCount(0)
  await heading.click()
  await page.getByText('Synthetic keyboard child', { exact: true }).hover()
  await page.keyboard.press('Delete')
  await expect(dialog).toContainText('Synthetic keyboard child')
  await dialog.getByRole('button', { name: 'Supprimer le dossier', exact: true }).click()
  await expect(page.getByText('Synthetic keyboard child', { exact: true })).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath('document-library-shortcuts.png'), animations: 'disabled' })
  await errors.settle()
  expect(errors()).toEqual([])
})
