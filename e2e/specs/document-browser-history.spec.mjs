import { createDocument } from '../documents.mjs'
import { test, expect } from '@playwright/test'
import { collectPageErrors } from '../page-errors.mjs'

test('browser and document arrows share visits in Documents, dialogs and Chat', async ({ page, request }) => {
  const errors = collectPageErrors(page)
  const fixture = await (await request.post('/api/__test/seed')).json()
  const refresh = page.waitForResponse(response => response.url().endsWith('/api/auth/refresh'))
  await page.goto('/user/login'); await refresh
  await page.locator('input[type=email]').fill(fixture.email)
  await page.locator('input[type=password]').fill(fixture.password)
  const authentication = page.waitForResponse(response => response.url().endsWith('/api/auth/login-json'))
  await page.locator('button[type=submit]').click()
  const session = await (await authentication).json()
  await expect(page.locator('input[type=password]')).toHaveCount(0)
  const headers = { Authorization: `Bearer ${session.access_token}`, 'X-Editorial-Profile-Version': '1' }
  async function create(title, html) {
    const response = await createDocument(request, { headers, data: {
      owner_agent_id: fixture.agent_id, title, node_kind: 'document',
      media_type: 'text/html', payload: { text: html },
    } })
    expect(response.ok(), await response.text()).toBeTruthy()
    return response.json()
  }
  const gamma = await create('Synthetic navigation Gamma', '<p>Gamma body</p>')
  const beta = await create('Synthetic navigation Beta', `<p>Beta body</p><p><a href="document://${gamma.id}">Open Gamma</a></p>`)
  const alpha = await create('Synthetic navigation Alpha', `<p>Alpha body</p><p><a href="document://${beta.id}">Open Beta</a></p>`)
  const previous = scope => scope.getByRole('button', { name: /^(Previous document|Document précédent)$/, exact: true })
  const next = scope => scope.getByRole('button', { name: /^(Next document|Document suivant)$/, exact: true })
  const body = scope => scope.locator('[data-editor-surface]')
  await errors.settle()
  await page.goto(`/documents?document_id=${alpha.id}`)
  await expect(body(page)).toContainText('Alpha body')
  await page.getByRole('link', { name: 'Open Beta', exact: true }).click({ modifiers: ['Control'] })
  await expect(body(page)).toContainText('Beta body')
  await expect(page).toHaveURL(new RegExp(`document_id=${beta.id}$`))
  await page.getByRole('link', { name: 'Open Gamma', exact: true }).click({ modifiers: ['Control'] })
  await expect(body(page)).toContainText('Gamma body')
  await page.goBack()
  await expect(body(page)).toContainText('Beta body')
  await previous(page.locator('.page-header')).click()
  await expect(body(page)).toContainText('Alpha body')
  await page.goForward()
  await expect(body(page)).toContainText('Beta body')
  await next(page.locator('.page-header')).click()
  await expect(body(page)).toContainText('Gamma body')
  await page.reload()
  await expect(body(page)).toContainText('Gamma body')
  await page.goBack()
  await expect(body(page)).toContainText('Beta body')
  await page.goForward()
  await expect(body(page)).toContainText('Gamma body')
  await page.goBack(); await page.goBack()
  await expect(body(page)).toContainText('Alpha body')

  await page.getByRole('link', { name: 'Open Beta', exact: true }).click()
  await page.getByRole('button', { name: /^(Open in a dialog|Ouvrir dans une modale)$/, exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(body(dialog)).toContainText('Beta body')
  await dialog.getByRole('link', { name: 'Open Gamma', exact: true }).click({ modifiers: ['Control'] })
  await expect(body(dialog)).toContainText('Gamma body')
  await page.evaluate(() => window.history.back())
  await expect(body(dialog)).toContainText('Beta body')
  await next(dialog).click()
  await expect(body(dialog)).toContainText('Gamma body')
  await expect(page).toHaveURL(new RegExp(`document_id=${alpha.id}$`))
  await dialog.getByRole('button', { name: /^(Close|Fermer)$/, exact: true }).first().click()
  await expect(dialog).toHaveCount(0)
  await expect(body(page)).toContainText('Alpha body')

  await errors.settle()
  await page.goto(`/chat?room=${fixture.rooms[0]}`)
  await page.getByRole('button', { name: /^(Search accessible documents|Rechercher un document accessible)$/, exact: true }).click()
  await page.getByLabel(new RegExp(`^(Open document|Ouvrir le document) ${alpha.title}$`)).click()
  const pane = page.locator('.chat-document-pane')
  await expect(body(pane)).toContainText('Alpha body')
  await pane.getByRole('link', { name: 'Open Beta', exact: true }).click({ modifiers: ['Control'] })
  await expect(body(pane)).toContainText('Beta body')
  await pane.getByRole('link', { name: 'Open Gamma', exact: true }).click({ modifiers: ['Control'] })
  await expect(body(pane)).toContainText('Gamma body')
  await page.evaluate(() => window.history.back())
  await expect(body(pane)).toContainText('Beta body')
  await previous(pane).click()
  await expect(body(pane)).toContainText('Alpha body')
  await page.evaluate(() => window.history.forward())
  await expect(body(pane)).toContainText('Beta body')
  await expect(page).toHaveURL(new RegExp(`/chat\\?room=${fixture.rooms[0]}$`))
  await expect(page.locator('.conversation-pane')).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('chat-browser-history.png') })
  expect(errors()).toEqual([])
})
