  const endSlot = page.getByRole('button', { name: `Créer un événement · ${tomorrow} 11:00`, exact: true })
  await expect(startSlot).toBeVisible()
  const startBox = await startSlot.boundingBox(), endBox = await endSlot.boundingBox()
