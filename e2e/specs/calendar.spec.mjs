  await expect(editor.getByRole('button', { name: 'Enregistrer', exact: true })).toBeInViewport()
  await testInfo.attach('event-editor-scroll-layout', { body: JSON.stringify(await editor.locator('.galaris-dialog-body').evaluate(element => ({ clientHeight: element.clientHeight, scrollHeight: element.scrollHeight, overflow: getComputedStyle(element).overflowY }))), contentType: 'application/json' })
  await page.screenshot({ path: testInfo.outputPath('event-editor-scroll.png'), fullPage: true, animations: 'disabled' })
