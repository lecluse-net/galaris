  await editor.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  const response = await eventSaved
  expect(response.ok(), await response.text()).toBeTruthy()
  const receipt = await response.json(), path = `/api/calendars/${receipt.calendar_id}/events/${receipt.event_id}`
