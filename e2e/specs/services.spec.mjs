import { test, expect } from '@playwright/test'
import { notificationPrompt } from '../notification-prompt.mjs'
import { collectPageErrors } from '../page-errors.mjs'
import fs from 'node:fs/promises'

test('A bundled service preset is saved, reopened and exported as one YAML with its icon in the assembled application', async ({ page, request }, testInfo) => {
  const errors = collectPageErrors(page)
  const fixture = await (await request.post('/api/__test/seed?mode=process-human')).json()
  await page.addLocatorHandler(notificationPrompt(page), prompt => prompt.getByRole('button', { name: 'Plus tard', exact: true }).click())
  await page.goto('/user/login')
  await page.locator('input[type=email]').fill(fixture.email)
  await page.locator('input[type=password]').fill(fixture.password)
  const authenticated = page.waitForResponse(response => response.url().endsWith('/api/auth/login-json'))
  await page.locator('button[type=submit]').click()
  const session = await (await authenticated).json()
  const headers = { Authorization: `Bearer ${session.access_token}` }
  await expect(page.locator('input[type=password]')).toHaveCount(0)
  await page.goto('/services')
  await page.getByRole('tab', { name: 'Catalogue', exact: true }).click()
  const provider = page.getByRole('row').filter({ has: page.getByText('GitLab', { exact: true }) })
  await provider.getByRole('button', { name: 'Configurer une copie', exact: true }).click()
  const editor = page.getByRole('dialog')
  await editor.getByLabel('Nom technique *', { exact: true }).fill('synthetic-catalog-provider')
  await editor.getByLabel('Libellé *', { exact: true }).fill('Synthetic catalog provider')
  await editor.getByRole('button', { name: 'Créer', exact: true }).click()
  await expect(editor).toHaveCount(0)
  const saved = (await (await request.get('/api/services', { headers })).json()).find(service => service.code === 'synthetic-catalog-provider')
  expect(saved.icon.media_type).toBe('image/svg+xml')
  expect(saved.icon.data).toContain('<svg')
  expect(saved.catalog.version).toBe('1.0.0')
  expect(saved.rest_config.auth.param).toBe('token')
  expect(saved.connection_schema.params.token.type).toBe('password')
  await page.reload()
  const row = page.getByRole('row').filter({ has: page.getByText('Synthetic catalog provider', { exact: true }) })
  await expect(row).toBeVisible()
  await expect(row.locator('img')).toHaveAttribute('src', /^data:image\/svg\+xml/)
  const download = page.waitForEvent('download')
  await row.getByRole('button', { name: 'Exporter en YAML', exact: true }).click()
  const file = await download
  const exported = await fs.readFile(await file.path(), 'utf8')
  expect(exported).toContain('image/svg+xml')
  expect(exported).toContain('<svg')
  expect(exported).toContain('synthetic-catalog-provider')
  await page.screenshot({ path: testInfo.outputPath('services-desktop.png'), fullPage: true, animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByText('Synthetic catalog provider', { exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('services-mobile.png'), fullPage: true, animations: 'disabled' })
  await errors.settle()
  expect(errors()).toEqual([])
})
