import { test, expect } from '@playwright/test'
import { collectPageErrors } from '../page-errors.mjs'

for (const width of [1440, 390]) {
  test(`human personal skill administration persists through reopening at ${width}px`, async ({ page, request }, testInfo) => {
    await page.setViewportSize({ width, height: 900 })
    const errors = collectPageErrors(page)
    const fixture = await (await request.post('/api/__test/seed?mode=personal-skills')).json()
    await page.addLocatorHandler(page.getByRole('button', { name: 'Plus tard', exact: true }), button => button.click())
    await page.goto('/user/login')
    await page.locator('input[type=email]').fill(fixture.email)
    await page.locator('input[type=password]').fill(fixture.password)
    const login = page.waitForResponse(response => response.url().endsWith('/api/auth/login-json'))
    await page.locator('button[type=submit]').click()
    const session = await (await login).json()
    await expect(page.locator('input[type=password]')).toHaveCount(0)
    const headers = { Authorization: `Bearer ${session.access_token}` }
    const [guide, disposable] = fixture.personal_skills
    const failures = []
    page.on('response', response => {
      if (new URL(response.url()).pathname.startsWith('/api/') && response.status() >= 400) failures.push(`${response.status()} ${response.url()}`)
    })
    await errors.settle()
    await page.goto('/skill')
    if (width < 1024) {
      const backdrop = page.locator('.q-drawer__backdrop')
      if (await backdrop.isVisible()) await backdrop.click({ position: { x: 380, y: 400 } })
    }
    await page.getByRole('tab', { name: 'Compétences personnelles', exact: true }).click()
    await page.getByRole('combobox', { name: 'Filtrer par agent', exact: true }).click()
    await page.getByRole('option', { name: fixture.agent_label, exact: true }).click()
    await page.getByText(guide.label, { exact: true }).click()
    let dialog = page.getByRole('dialog')
    await expect(dialog.getByLabel('Libellé', { exact: true })).not.toHaveAttribute('readonly')
    const originalSource = (await (await request.get(`/api/skills/personal/${guide.id}/content`, { headers })).json()).content
    await dialog.getByLabel('Libellé', { exact: true }).fill(`Renamed ${guide.label}`)
    await dialog.getByRole('button', { name: 'Enregistrer', exact: true }).click()
    await expect(dialog.getByRole('button', { name: 'Enregistrer', exact: true })).toHaveCount(0)
    await expect(dialog.getByLabel('Libellé', { exact: true })).toHaveValue(`Renamed ${guide.label}`)
    expect((await (await request.get(`/api/skills/personal/${guide.id}`, { headers })).json()).skill.label).toBe(`Renamed ${guide.label}`)
    expect((await (await request.get(`/api/skills/personal/${guide.id}/content`, { headers })).json()).content).toBe(originalSource)
    await dialog.getByRole('button', { name: 'Modifier', exact: true }).click()
    const editedLabel = `Edited ${guide.label}`
    await dialog.getByLabel('Libellé', { exact: true }).fill(editedLabel)
    const source = `---\nname: ${guide.code}\ndescription: Synthetic edited private instructions.\n---\nVerified human edit\n`
    await dialog.getByLabel('Source', { exact: true }).fill(source)
    await dialog.getByRole('button', { name: 'Enregistrer', exact: true }).click()
    await expect(dialog.getByText('Verified human edit', { exact: true })).toBeVisible()
    const read = await request.get(`/api/skills/personal/${guide.id}/content`, { headers })
    expect((await read.json()).content).toBe(source)
    expect((await (await request.get(`/api/skills/personal/${guide.id}`, { headers })).json()).skill.label).toBe(editedLabel)
    await dialog.getByRole('button', { name: 'Désactiver', exact: true }).click()
    await expect(dialog.getByRole('button', { name: 'Activer', exact: true })).toBeVisible()
    await dialog.getByRole('button', { name: 'Annuler', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await page.getByText(editedLabel, { exact: true }).click()
    dialog = page.getByRole('dialog')
    await expect(dialog.getByText('Verified human edit', { exact: true })).toBeVisible()
    await expect(dialog.getByRole('button', { name: 'Activer', exact: true })).toBeVisible()
    await expect(dialog.getByLabel('Libellé', { exact: true })).toHaveValue(editedLabel)
    await page.screenshot({ path: testInfo.outputPath('personal-skill-edited.png'), fullPage: true, animations: 'disabled' })
    await dialog.getByRole('button', { name: 'Convertir en compétence générique', exact: true }).click()
    const confirmation = page.getByRole('dialog').last()
    await confirmation.getByLabel('Code', { exact: true }).fill(`released-${guide.code}`)
    await confirmation.getByRole('button', { name: 'Convertir en compétence générique', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await page.getByRole('tab', { name: 'Compétences', exact: true }).click()
    await expect(page.getByText(editedLabel, { exact: true })).toBeVisible()
    const generic = (await (await request.get('/api/skills', { headers })).json()).find(skill => skill.id === guide.id)
    expect(generic.code).toBe(`released-${guide.code}`)
    await page.getByText(editedLabel, { exact: true }).click()
    const libraryViewer = page.getByRole('dialog')
    await expect(libraryViewer.getByText('Verified human edit', { exact: true })).toBeVisible()
    await expect(libraryViewer.getByRole('button', { name: 'Enregistrer', exact: true })).toHaveCount(0)
    await libraryViewer.getByRole('button', { name: 'Annuler', exact: true }).click()
    await expect(libraryViewer).toHaveCount(0)
    const grant = await request.put(`/api/skills/${guide.id}/authorization/global`, {
      headers, params: { agent_id: fixture.agent_id }, data: { state: 'enabled' },
    })
    expect(grant.ok()).toBe(true)
    await page.getByRole('button', { name: 'Passer en personnel', exact: true }).click()
    const ownership = page.getByRole('dialog')
    await ownership.getByRole('combobox', { name: 'Agent propriétaire', exact: true }).click()
    await page.getByRole('option', { name: fixture.agent_label, exact: true }).click()
    await expect(page.getByRole('option')).toHaveCount(0)
    await page.screenshot({ path: testInfo.outputPath('make-skill-personal.png'), fullPage: true, animations: 'disabled' })
    await ownership.getByRole('button', { name: 'Passer en personnel', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await expect(page.getByText(editedLabel, { exact: true })).toHaveCount(0)
    const privatized = await (await request.get(`/api/skills/personal/${guide.id}`, { headers })).json()
    expect(privatized.skill.owner_agent_id).toBe(fixture.agent_id)
    expect(privatized.skill.enabled).toBe(true)
    expect((await request.get('/api/skills/authorizations', { headers, params: { skill_id: guide.id } })).status()).toBe(404)
    await page.getByRole('tab', { name: 'Compétences personnelles', exact: true }).click()
    await page.getByText(editedLabel, { exact: true }).click()
    await expect(page.getByRole('dialog').getByText('Verified human edit', { exact: true })).toBeVisible()
    const ownerSelect = page.getByRole('dialog').getByRole('combobox', { name: 'Agent propriétaire', exact: true })
    await ownerSelect.click()
    await page.getByRole('option', { name: fixture.recipient_label, exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Changer de propriétaire', exact: true }).click()
    await page.getByRole('dialog').last().getByRole('button', { name: 'Changer de propriétaire', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    const transferred = await (await request.get(`/api/skills/personal/${guide.id}`, { headers })).json()
    expect(transferred.skill.owner_agent_id).toBe(fixture.recipient_id)
    expect(transferred.skill.enabled).toBe(true)
    expect((await (await request.get(`/api/skills/personal/${guide.id}/content`, { headers })).json()).content).toContain('Verified human edit')
    await expect(page.getByText(editedLabel, { exact: true })).toHaveCount(0)
    await page.getByRole('combobox', { name: 'Filtrer par agent', exact: true }).click()
    await page.getByRole('option', { name: fixture.recipient_label, exact: true }).click()
    await page.getByText(editedLabel, { exact: true }).click()
    await expect(page.getByRole('dialog').getByRole('combobox', { name: 'Agent propriétaire', exact: true })).toHaveValue(fixture.recipient_label)
    await page.getByRole('dialog').getByRole('button', { name: 'Annuler', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await page.getByRole('combobox', { name: 'Filtrer par agent', exact: true }).click()
    await page.getByRole('option', { name: fixture.agent_label, exact: true }).click()
    await page.getByText(disposable.label, { exact: true }).click({ button: 'right' })
    await page.getByRole('menuitem', { name: 'Supprimer', exact: true }).click()
    await page.getByRole('dialog').last().getByRole('button', { name: 'Supprimer', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    const listed = await request.get('/api/skills/personal', { headers, params: { owner_agent_id: fixture.agent_id } })
    expect((await listed.json()).items.some(skill => skill.id === disposable.id)).toBe(false)
    await errors.settle()
    expect(errors()).toEqual([])
    expect(failures).toEqual([])
  })
}
