import { test, expect } from '@playwright/test'
import { collectPageErrors } from '../page-errors.mjs'

test.use({ serviceWorkers: 'allow' })

test('local file drops create editable documents at their destination and preserve them after reopening', async ({ page, request }, testInfo) => {
  const pageErrors = collectPageErrors(page)
  const seed = await request.post('/api/__test/seed')
  expect(seed.ok()).toBeTruthy()
  const fixture = await seed.json()
  await page.goto('/user/login')
  await page.locator('input[type=email]').fill(fixture.email)
  await page.locator('input[type=password]').fill(fixture.password)
  const authenticated = page.waitForResponse(response => response.url().endsWith('/api/auth/login-json'))
  await page.locator('button[type=submit]').click()
  const session = await (await authenticated).json()
  await expect(page.locator('input[type=password]')).toHaveCount(0)
  const headers = { Authorization: `Bearer ${session.access_token}` }
  const folderResponse = await request.post('/api/documents/tags', { headers, data: { name: 'Synthetic file imports', parent_id: null } })
  expect(folderResponse.ok()).toBeTruthy()
  const folder = await folderResponse.json()
  await pageErrors.settle()
  await page.goto('/documents')
  const destination = page.getByText(folder.name, { exact: true }).locator('xpath=ancestor::div[contains(@class,"tag-row")][1]')
  const file = await page.evaluateHandle(() => {
    const data = new DataTransfer()
    data.items.add(new File([' {"value":42}\n'], 'Synthetic values.json', { type: 'application/json' }))
    return data
  })
  await destination.dispatchEvent('dragover', { dataTransfer: file })
  await page.screenshot({ path: testInfo.outputPath('file-drop-target.png'), animations: 'disabled' })
  const createdResponse = page.waitForResponse(response => new URL(response.url()).pathname === '/api/documents/import')
  await destination.dispatchEvent('drop', { dataTransfer: file })
  await file.dispose()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toContainText('Synthetic values.json')
  await dialog.getByRole('button', { name: /^(Importer|Import) \(1\)$/ }).click()
  const response = await createdResponse
  expect(response.status(), await response.text()).toBe(201)
  const document = await response.json()
  await expect(dialog.getByRole('row').filter({ hasText: 'Synthetic values.json' })).toHaveCount(0)
  await dialog.getByRole('button', { name: /^(Fermer|Close)$/ }).first().click()
  const editor = page.locator('textarea.code-editor')
  await expect(editor).toHaveValue(' {"value":42}\n')
  await expect(editor).toBeEditable()
  await expect(page.getByRole('tree').getByText('Synthetic values', { exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('file-import-editor.png'), animations: 'disabled' })
  const savedResponse = page.waitForResponse(response => new URL(response.url()).pathname === `/api/documents/${document.id}` && response.request().method() === 'PATCH')
  await editor.fill('{"value":43}')
  expect((await savedResponse).ok()).toBeTruthy()
  const membership = await request.post('/api/documents/library', { headers, data: { tag_id: folder.id, classification: 'all', limit: 50 } })
  expect(membership.ok()).toBeTruthy()
  expect((await membership.json()).entries.map(entry => entry.item.id)).toContain(document.id)
  await pageErrors.settle()
  await page.reload()
  await expect(editor).toHaveValue('{"value":43}')
  await page.getByText(folder.name, { exact: true }).click()
  const parent = page.getByRole('tree').getByText('Synthetic values', { exact: true }).locator('xpath=ancestor::div[contains(@class,"document-branch-row")][1]')
  const notes = await page.evaluateHandle(() => {
    const data = new DataTransfer()
    data.items.add(new File(['# Synthetic child\n\nImported **notes**.'], 'Synthetic child.md', { type: 'text/markdown' }))
    return data
  })
  await parent.dispatchEvent('dragover', { dataTransfer: notes })
  const childResponse = page.waitForResponse(response => new URL(response.url()).pathname === '/api/documents/import')
  await parent.dispatchEvent('drop', { dataTransfer: notes })
  await notes.dispose()
  await dialog.getByRole('button', { name: /^(Importer|Import) \(1\)$/ }).click()
  const childResult = await childResponse
  expect(childResult.status(), await childResult.text()).toBe(201)
  const child = await childResult.json()
  await expect(dialog.getByRole('row').filter({ hasText: 'Synthetic child.md' })).toHaveCount(0)
  await dialog.getByRole('button', { name: /^(Fermer|Close)$/ }).first().click()
  await expect(page.locator('[data-editor-surface]')).toContainText('Synthetic child')
  await expect(page.locator('[data-editor-surface]')).toContainText('Imported notes.')
  const nested = await request.post('/api/documents/library', { headers, data: { parent_document_id: document.id, include_descendants: false, limit: 50 } })
  expect(nested.ok()).toBeTruthy()
  expect((await nested.json()).entries.map(entry => [entry.item.id, entry.parent_document_id])).toEqual([[child.id, document.id]])
  await destination.click({ button: 'right' })
  await page.getByRole('menuitem', { name: /^(Nouveau document depuis|New document from)/ }).click()
  const original = Buffer.from([0, 19, 255, 65, 66, 67])
  await dialog.locator('input[type=file]').setInputFiles({ name: 'Synthetic binary.opaque', mimeType: 'application/octet-stream', buffer: original })
  await expect(dialog.getByRole('row').filter({ hasText: 'Synthetic binary.opaque' })).toContainText(/Pièce jointe uniquement|Attachment only/)
  const attachedResponse = page.waitForResponse(response => new URL(response.url()).pathname === '/api/documents/import')
  await dialog.getByRole('button', { name: /^(Importer|Import) \(1\)$/ }).click()
  const attachedResult = await attachedResponse
  expect(attachedResult.status(), await attachedResult.text()).toBe(201)
  const attached = await attachedResult.json()
  await expect(dialog.getByRole('row').filter({ hasText: 'Synthetic binary.opaque' })).toHaveCount(0)
  await dialog.getByRole('button', { name: /^(Fermer|Close)$/ }).first().click()
  const blank = await request.get(`/api/documents/${attached.id}`, { headers })
  expect(blank.ok()).toBeTruthy()
  expect((await blank.json()).item.payload.text).toBe('')
  const attachments = await request.get(`/api/documents/${attached.id}/attachments`, { headers })
  expect(attachments.ok()).toBeTruthy()
  const files = await attachments.json()
  expect(files).toHaveLength(1)
  expect(files[0].name).toBe('Synthetic binary.opaque')
  const stored = await request.get(`/api/documents/${attached.id}/attachments/${files[0].id}`, { headers })
  expect(stored.ok()).toBeTruthy()
  expect(await stored.body()).toEqual(original)
  await destination.click({ button: 'right' })
  await page.getByRole('menuitem', { name: /^(Nouveau document depuis|New document from)/ }).click()
  await dialog.locator('input[type=file]').setInputFiles({ name: 'Synthetic page.html', mimeType: 'text/html',
    buffer: Buffer.from('<html><head><script src="/local/library.js"></script></head><body><h1 onclick="run()">Synthetic page</h1><p>Kept content</p><script src="https://unapproved.invalid/app.js"></script></body></html>') })
  const htmlResponse = page.waitForResponse(response => new URL(response.url()).pathname === '/api/documents/import')
  await dialog.getByRole('button', { name: /^(Importer|Import) \(1\)$/ }).click()
  const htmlResult = await htmlResponse
  expect(htmlResult.status(), await htmlResult.text()).toBe(201)
  const htmlDocument = await htmlResult.json()
  await expect(dialog.getByRole('row').filter({ hasText: 'Synthetic page.html' })).toHaveCount(0)
  const cleaned = await request.get(`/api/documents/${htmlDocument.id}`, { headers })
  expect(cleaned.ok()).toBeTruthy()
  expect((await cleaned.json()).item.payload.text).toBe('<h1>Synthetic page</h1><p>Kept content</p>')
  await dialog.getByRole('button', { name: /^(Fermer|Close)$/ }).first().click()
  await destination.click({ button: 'right' })
  await page.getByRole('menuitem', { name: /^(Nouveau document depuis|New document from)/ }).click()
  // Synthetic ZIP: one empty folder, one Markdown file and one JSON file.
  const archive = Buffer.from('UEsDBBQAAAAIAAAAISgAAAAAAgAAAAAAAAAGAAAAZW1wdHkvAwBQSwMEFAAAAAgAAAAhKEAqhFsdAAAAGwAAAA8AAABub3Rlcy9yZXBvcnQubWRTVgiuzCvJSC3JTFZILErOyCxLTVEoSi3ILyoBAFBLAwQUAAAACAAAACEoNxGu5Q4AAAAMAAAAEQAAAG5vdGVzL3ZhbHVlcy5qc29uq1YqS8wpTVWyMjGqBQBQSwECFAMUAAAACAAAACEoAAAAAAIAAAAAAAAABgAAAAAAAAAAAAAAgAEAAAAAZW1wdHkvUEsBAhQDFAAAAAgAAAAhKEAqhFsdAAAAGwAAAA8AAAAAAAAAAAAAAIABJgAAAG5vdGVzL3JlcG9ydC5tZFBLAQIUAxQAAAAIAAAAISg3Ea7lDgAAAAwAAAARAAAAAAAAAAAAAACAAXAAAABub3Rlcy92YWx1ZXMuanNvblBLBQYAAAAAAwADALAAAACtAAAAAAA=', 'base64')
  await dialog.locator('input[type=file]').setInputFiles({ name: 'Synthetic tree.zip', mimeType: 'application/zip', buffer: archive })
  await expect(dialog.getByText(/^(Dans un sous-répertoire dédié|Into a dedicated subfolder)$/)).toBeVisible()
  await dialog.screenshot({ path: testInfo.outputPath('zip-import-dialog.png'), animations: 'disabled' })
  await dialog.getByRole('button', { name: /^(Importer|Import) \(1\)$/ }).click()
  await expect(dialog.getByRole('row').filter({ hasText: 'Synthetic tree.zip' })).toHaveCount(0)
  const tags = (await (await request.get('/api/documents/tags', { headers })).json()).tags
  const root = tags.find(tag => tag.name === 'Synthetic tree' && tag.parent_id === folder.id)
  expect(root).toBeTruthy()
  expect(tags.some(tag => tag.name === 'empty' && tag.parent_id === root.id)).toBe(true)
  const notesFolder = tags.find(tag => tag.name === 'notes' && tag.parent_id === root.id)
  expect(notesFolder).toBeTruthy()
  const contents = await request.post('/api/documents/library', { headers, data: { tag_id: notesFolder.id, classification: 'all', limit: 50 } })
  expect(contents.ok()).toBeTruthy()
  const entries = (await contents.json()).entries
  expect(entries.map(entry => entry.item.title).sort()).toEqual(['report', 'values'])
  const report = entries.find(entry => entry.item.title === 'report').item
  const importedReport = await request.get(`/api/documents/${report.id}`, { headers })
  expect(importedReport.ok()).toBeTruthy()
  expect((await importedReport.json()).item.payload.text).toBe('<h1>Synthetic archived report</h1>')
  await dialog.getByRole('button', { name: /^(Fermer|Close)$/ }).first().click()
  await destination.click({ button: 'right' })
  await page.getByRole('menuitem', { name: /^(Nouveau document depuis|New document from)/ }).click()
  await dialog.locator('input[type=file]').setInputFiles({ name: 'Synthetic direct.zip', mimeType: 'application/zip', buffer: archive })
  await dialog.getByRole('combobox', { name: /Mode d’import du ZIP|ZIP import mode/ }).click()
  await page.getByRole('option', { name: /^(Dans le répertoire courant|Into the current folder)$/ }).click()
  await dialog.getByRole('button', { name: /^(Importer|Import) \(1\)$/ }).click()
  await expect(dialog.getByRole('row').filter({ hasText: 'Synthetic direct.zip' })).toHaveCount(0)
  const directTags = (await (await request.get('/api/documents/tags', { headers })).json()).tags
  expect(directTags.some(tag => tag.name === 'Synthetic direct')).toBe(false)
  const directNotes = directTags.find(tag => tag.name === 'notes' && tag.parent_id === folder.id)
  expect(directNotes).toBeTruthy()
  const directContents = await request.post('/api/documents/library', { headers, data: { tag_id: directNotes.id, classification: 'all', limit: 50 } })
  expect(directContents.ok()).toBeTruthy()
  expect((await directContents.json()).entries.map(entry => entry.item.title).sort()).toEqual(['report', 'values'])
  await dialog.getByRole('button', { name: /^(Fermer|Close)$/ }).first().click()
  await pageErrors.settle()
  expect(pageErrors()).toEqual([])
})
