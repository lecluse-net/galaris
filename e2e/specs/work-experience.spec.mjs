import { test, expect } from '@playwright/test'
import { collectPageErrors } from '../page-errors.mjs'

test('Welcome keeps the first mission and its saved document available on desktop and mobile', async ({ page, request }) => {
  const errors = collectPageErrors(page)
  const fixture = await (await request.post('/api/__test/seed?mode=first-mission')).json()
  const refresh = page.waitForResponse(response => response.url().endsWith('/api/auth/refresh'))
  await page.goto('/user/login'); await refresh
  await page.locator('input[type=email]').fill(fixture.email)
  await page.locator('input[type=password]').fill(fixture.password)
  const login = page.waitForResponse(response => response.url().endsWith('/api/auth/login-json'))
  await page.locator('button[type=submit]').click()
  const session = await (await login).json()
  await expect(page.locator('input[type=password]')).toHaveCount(0)
  const headers = { Authorization: `Bearer ${session.access_token}`, 'X-Editorial-Profile-Version': '1' }
  expect((await request.put('/api/params/DEFAULT_LANGUAGE', { headers, data: { value: 'fr' } })).ok()).toBeTruthy()
  await errors.settle()
  await page.goto('/welcome')
  await page.getByRole('combobox', { name: 'Agent', exact: true }).click()
  await page.getByRole('option', { name: new RegExp(`Browser.*${fixture.email.slice(4, fixture.email.indexOf('@'))}`) }).click()
  const prompt = page.getByRole('textbox', { name: 'Demande à confier', exact: true })
  await prompt.fill(`@exec @standard ${await prompt.inputValue()}`)
  await page.getByRole('button', { name: 'Lancer la mission', exact: true }).click()
  const document = page.getByRole('link', { name: 'Synthetic first mission summary', exact: true })
  await expect(document).toBeVisible({ timeout: 45_000 })
  await expect(page.getByRole('region', { name: 'Réaliser votre première mission', exact: true }).getByRole('status')).toContainText('son document est disponible')
  const href = await document.getAttribute('href')
  await page.screenshot({ path: test.info().outputPath('first-mission-complete.png') })
  await errors.settle()
  await page.goto('/welcome')
  await expect(document).toHaveAttribute('href', href)
  await document.click()
  await expect(page.locator('[data-editor-surface]')).toContainText('The venue is booked.')
  await errors.settle()
  await page.goto('/')
  await expect(page.locator('.home-page')).toBeVisible()
  await page.setViewportSize({ width: 390, height: 1000 })
  await errors.settle()
  await page.goto('/')
  await expect(page.locator('.home-page')).toBeVisible()
  const backdrop = page.locator('.q-drawer__backdrop')
  if (await backdrop.isVisible()) await backdrop.click({ position: { x: 380, y: 200 } })
  await errors.settle()
  await page.screenshot({ path: test.info().outputPath('home-mobile.png'), fullPage: true, animations: 'disabled' })
  await page.goto('/welcome')
  await expect(document).toHaveAttribute('href', href)
  await errors.settle()
  await page.screenshot({ path: test.info().outputPath('welcome-first-mission-mobile.png'), fullPage: true, animations: 'disabled' })
  await errors.settle()
  expect(errors()).toEqual([])
})
