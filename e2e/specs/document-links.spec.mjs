import { createDocument } from '../documents.mjs'
import { test, expect } from '@playwright/test'
import { collectPageErrors } from '../page-errors.mjs'

test('documents dropped from the list and tree persist as titled links and reversible cards', async ({ page, request, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  const errors = collectPageErrors(page)
  const fixture = await (await request.post('/api/__test/seed')).json()
  const refresh = page.waitForResponse(response => response.url().endsWith('/api/auth/refresh'))
  await errors.settle()
  await page.goto('/user/login'); await refresh
  await page.locator('input[type=email]').fill(fixture.email)
  await page.locator('input[type=password]').fill(fixture.password)
  const authentication = page.waitForResponse(response => response.url().endsWith('/api/auth/login-json'))
  await page.locator('button[type=submit]').click()
  const session = await (await authentication).json()
  await expect(page.locator('input[type=password]')).toHaveCount(0)
  const headers = { Authorization: `Bearer ${session.access_token}`, 'X-Editorial-Profile-Version': '1' }
  async function checked(response) { expect(response.ok(), await response.text()).toBeTruthy(); return response.json() }
  const target = await checked(await createDocument(request, { headers, data: {
    owner_agent_id: fixture.agent_id, title: `Synthetic report ${fixture.agent_id}`, node_kind: 'document',
    media_type: 'text/html', payload: { text: '<p>Preserve the report body</p><p>Another paragraph</p>' },
  } }))
  const user = await checked(await request.get('/api/auth/me', { headers }))
  const createdSource = await checked(await request.post('/api/documents', { headers, data: {
    owner_kind: 'user', owner_id: user.id, actor_agent_id: fixture.agent_id, title: `Synthetic reference ${fixture.agent_id}`,
  } }))
  const source = await checked(await request.patch(`/api/documents/${createdSource.id}`, { headers, data: {
    expected_revision: createdSource.revision, expected_lock_version: createdSource.lock_version,
    payload: { text: '<p>Independent referenced document</p>' },
  } }))
  const deniedToContainingAgent = await request.get(`/api/documents/${source.id}?agent_id=${fixture.agent_id}`, { headers })
  expect(deniedToContainingAgent.status()).toBe(403)
  expect((await request.get(`/api/documents/${source.id}`, { headers })).ok()).toBeTruthy()
  await errors.settle()
  await page.goto(`/documents?document_id=${target.id}`)
  const editor = page.locator('[data-editor-surface]')
  await expect(editor).toContainText('Preserve the report body')
  const list = page.getByRole('list', { name: /^(Unclassified documents|Documents non classés)$/, exact: true })
  async function dropAtEnd(row, paragraph) {
    const bounds = await paragraph.boundingBox()
    expect(bounds).not.toBeNull()
    await row.dragTo(paragraph, { targetPosition: { x: bounds.width - 5, y: bounds.height / 2 } })
  }
  const saved = () => page.waitForResponse(response => new URL(response.url()).pathname === `/api/documents/${target.id}` && response.request().method() === 'PATCH')
  const firstSave = saved()
  await dropAtEnd(list.getByText(source.title, { exact: true }), editor.locator('p').first())
  await expect(editor.locator('a')).toHaveText(source.title)
  expect((await firstSave).ok()).toBeTruthy()
  await editor.locator('a').click()
  const cardSave = saved()
  await page.getByRole('button', { name: /^(Show card|Afficher une carte)$/, exact: true }).click()
  await expect(editor.locator('.galaris-link-card > p').first()).toHaveText(source.title)
  expect((await cardSave).ok()).toBeTruthy()
  await expect(editor.locator('.document-thumbnail img')).toBeVisible()
  const identifier = editor.locator('.document-citation-identifier')
  await expect(identifier).toHaveText(source.id)
  await identifier.click()
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toBe(source.id)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.reload()
  await expect(editor.locator('.galaris-link-card > p').first()).toHaveText(source.title)
  await editor.locator('.galaris-link-card > p').first().click()
  const linkSave = saved()
  await page.getByRole('button', { name: /^(Show URL|Afficher l’URL)$/, exact: true }).click()
  await expect(editor.locator('a')).toHaveText(source.title)
  expect((await linkSave).ok()).toBeTruthy()

  const folder = await checked(await request.post('/api/documents/tags', { headers, data: { name: `Synthetic references ${fixture.agent_id}`, parent_id: null } }))
  const filed = await request.put(`/api/documents/${source.id}/tags`, { headers, data: { tag_id: folder.id } })
  expect(filed.ok(), await filed.text()).toBeTruthy()
  await page.getByText(folder.name, { exact: true }).click()
  const tree = page.locator('.document-tree')
  await expect(tree.getByText(source.title, { exact: true })).toBeVisible()
  const secondSave = saved()
  await dropAtEnd(tree.getByText(source.title, { exact: true }), editor.locator('p').last())
  await expect(editor.locator('a')).toHaveCount(2)
  expect((await secondSave).ok()).toBeTruthy()
  await page.reload()
  await expect(editor.locator('a')).toHaveCount(2)
  for (const link of await editor.locator('a').all()) await expect(link).toHaveText(source.title)
  const persisted = await checked(await request.get(`/api/documents/${target.id}`, { headers }))
  expect(persisted.item.payload.text.match(new RegExp(`document://${source.id}`, 'g'))).toHaveLength(2)
  expect(persisted.item.payload.text).toContain('Preserve the report body')
  const classified = await checked(await request.post('/api/documents/library', { headers, data: { tag_id: folder.id, limit: 50 } }))
  expect(classified.entries.map(entry => entry.item.id)).toContain(source.id)
  await editor.locator('a').first().click({ modifiers: ['Control'] })
  await expect(page).toHaveURL(new RegExp(`/documents\\?document_id=${source.id}$`))
  await expect(editor).toHaveText('Independent referenced document')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: /^(Previous document|Document précédent)$/, exact: true }).click()
  await expect(editor).toContainText('Preserve the report body')
  await page.getByRole('button', { name: /^(Next document|Document suivant)$/, exact: true }).click()
  await expect(editor).toHaveText('Independent referenced document')
  await page.screenshot({ path: test.info().outputPath('document-links.png'), fullPage: true })

  // A document opened from Files owns a modal history; linked private documents
  // use the reader's own access rather than the containing Agent's scope.
  const agents = await checked(await request.get('/api/agents/selection?scope=management', { headers }))
  const actor = agents.find(agent => agent.id === fixture.agent_id)
  expect(actor).toBeTruthy()
  await page.goto('/files')
  await page.getByRole('button', { name: `Explorer les fichiers de ${actor.label}`, exact: true }).click()
  await page.getByText('Galaris document', { exact: true }).click()
  const openTarget = page.locator('.file-main').getByRole('button', { name: `Ouvrir ${target.title}`, exact: true })
  await openTarget.click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.locator('[data-editor-surface]')).toContainText('Preserve the report body')
  await dialog.getByRole('link', { name: source.title, exact: true }).first().click({ modifiers: ['Control'] })
  await expect(dialog.locator('[data-editor-surface]')).toHaveText('Independent referenced document')
  await expect(dialog).toHaveCount(1)
  await expect(page).toHaveURL(/\/files$/)
  await dialog.getByRole('button', { name: /^(Previous document|Document précédent)$/, exact: true }).click()
  await expect(dialog.locator('[data-editor-surface]')).toContainText('Preserve the report body')
  await dialog.getByRole('button', { name: /^(Next document|Document suivant)$/, exact: true }).click()
  await expect(dialog.locator('[data-editor-surface]')).toHaveText('Independent referenced document')
  await page.screenshot({ path: test.info().outputPath('document-dialog-links.png'), fullPage: true })
  await page.locator('.q-dialog__backdrop').last().click({ position: { x: 5, y: 5 } })
  await expect(dialog).toHaveCount(0)
  await openTarget.click()
  await expect(dialog.locator('[data-editor-surface]')).toContainText('Preserve the report body')
  await expect(dialog.getByRole('button', { name: /^(Previous document|Document précédent)$/, exact: true })).toBeDisabled()
  expect(errors()).toEqual([])
})
