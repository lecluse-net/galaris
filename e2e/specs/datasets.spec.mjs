import { test, expect } from '@playwright/test'
import { collectPageErrors } from '../page-errors.mjs'

// Metadata, sharing, ownership, classification and navigation use the common
// Document journeys. This scenario retains Data's exact JSON/history guarantees.
test('a Data document preserves JSON, metadata and history in the common editor', async ({ page, request }) => {
  test.setTimeout(120_000)
  const errors = collectPageErrors(page)
  await page.addLocatorHandler(page.locator('.chat-notification-prompt'), prompt => prompt.getByRole('button', { name: 'Plus tard', exact: true }).click())
  await page.addLocatorHandler(page.locator('body:not(:has([role="dialog"])) .q-drawer__backdrop'), backdrop => backdrop.click({ position: { x: 380, y: 150 } }))
  const fixture = await (await request.post('/api/__test/seed')).json()
  await page.goto('/user/login')
  await page.locator('input[type=email]').fill(fixture.email)
  await page.locator('input[type=password]').fill(fixture.password)
  const login = page.waitForResponse(response => response.url().endsWith('/api/auth/login-json'))
  await page.locator('button[type=submit]').click()
  const session = await (await login).json()
  await expect(page.locator('input[type=password]')).toHaveCount(0)
  const headers = { Authorization: `Bearer ${session.access_token}` }
  const checked = async response => { expect(response.ok(), await response.text()).toBeTruthy(); return response.json() }
  const source = '{\n "accepted": false, "count": 0, "note": null\n}\n'
  const dataset = await checked(await request.post('/api/datasets', { headers, data: { title: 'Synthetic free JSON', content: source } }))
  const changed = '[0,false,null,{"different":"structure"}]'
  await checked(await request.put(`/api/datasets/${dataset.id}/content`, { headers, data: { content: changed, expected_revision: 1 } }))
  expect((await request.put(`/api/datasets/${dataset.id}/content`, { headers, data: { content: '{broken', expected_revision: 2 } })).status()).toBe(422)
  expect((await request.put(`/api/datasets/${dataset.id}/content`, { headers, data: { content: 'null', expected_revision: 1 } })).status()).toBe(409)
  await errors.settle()
  await page.goto(`/dataset/${dataset.id}`)
  const json = page.locator('textarea.code-editor')
  await expect(page).toHaveURL(new RegExp(`/documents\\?document_id=${dataset.id}$`))
  await expect(json).toHaveValue(changed)
  const title = page.getByRole('textbox', { name: /^(Titre|Title)$/, exact: true })
  await title.fill('Synthetic renamed Data')
  await expect.poll(async () => (await checked(await request.get(`/api/datasets/${dataset.id}`, { headers }))).title).toBe('Synthetic renamed Data')
  await json.fill('{"invalid":')
  await expect(page.getByRole('status', { name: /Corrigez les champs invalides|Fix invalid fields/ })).toBeVisible()
  expect((await checked(await request.get(`/api/datasets/${dataset.id}`, { headers }))).content).toBe(changed)
  await json.fill('{"saved":true}')
  await expect.poll(async () => (await checked(await request.get(`/api/datasets/${dataset.id}`, { headers }))).content).toBe('{"saved":true}')
  await page.reload()
  await expect(json).toHaveValue('{"saved":true}')
  await page.getByRole('button', { name: /^(Afficher l’historique du contenu|Open content history)$/, exact: true }).click()
  await page.getByRole('button', { name: /^Version 1\b/ }).click()
  await page.getByRole('button', { name: /^(Aperçu|Preview)$/, exact: true }).click()
  await expect(page.locator('textarea.code-editor')).toHaveValue(source)
  await page.getByRole('button', { name: /^(Restaurer cette version|Restore this version)$/, exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: /^(Restaurer cette version|Restore this version)$/, exact: true }).click()
  await expect.poll(async () => (await checked(await request.get(`/api/datasets/${dataset.id}`, { headers }))).content).toBe(source)
  await expect(title).toHaveValue('Synthetic renamed Data')
  await page.screenshot({ path: test.info().outputPath('data-document-desktop.png'), fullPage: true, animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.reload()
  await expect(json).toHaveValue(source)
  await page.screenshot({ path: test.info().outputPath('data-document-mobile.png'), fullPage: true, animations: 'disabled' })
  expect(errors()).toEqual([])
})
