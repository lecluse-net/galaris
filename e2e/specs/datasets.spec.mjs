import { test, expect } from '@playwright/test'

test('a Dataset preserves free JSON, revisions and restoration through its editor', async ({ page, request }) => {
  test.setTimeout(120_000)
  await page.addLocatorHandler(page.locator('.chat-notification-prompt'), prompt => prompt.getByRole('button', { name: 'Plus tard', exact: true }).click())
  await page.addLocatorHandler(page.locator('.q-drawer__backdrop'), backdrop => backdrop.click({ position: { x: 380, y: 150 } }))
  const fixture = await (await request.post('/api/__test/seed')).json()
  await page.goto('/user/login')
  await page.locator('input[type=email]').fill(fixture.email)
  await page.locator('input[type=password]').fill(fixture.password)
  const login = page.waitForResponse(response => response.url().endsWith('/api/auth/login-json'))
  await page.locator('button[type=submit]').click()
  const session = await (await login).json()
  await expect(page.locator('input[type=password]')).toHaveCount(0)
  const headers = { Authorization: `Bearer ${session.access_token}` }
  const checked = async response => { expect(response.ok(), await response.text()).toBeTruthy(); return response.json() }
  const source = '{\n "accepted": false, "count": 0, "note": null\n}\n'
  const dataset = await checked(await request.post('/api/datasets', { headers, data: { title: 'Synthetic free JSON', content: source } }))
  const other = await checked(await request.post('/api/datasets', { headers, data: { title: 'Synthetic second Dataset', content: '{"second":true}' } }))
  const document = await checked(await request.post('/api/memory/items', { headers: { ...headers, 'X-Editorial-Profile-Version': '1' }, data: {
    owner_agent_id: fixture.agent_id, title: 'Synthetic Dataset consumer', node_kind: 'document', media_type: 'text/html',
    payload: { text: `<form data-dataset="${dataset.uri}"><p>Synthetic application</p></form>` },
  } }))
  const written = await checked(await request.put(`/api/datasets/${dataset.id}/content`, { headers, data: {
    content: '[0,false,null,{"different":"structure"}]', expected_revision: 1 } }))
  const invalid = await request.put(`/api/datasets/${dataset.id}/content`, { headers, data: { content: '{broken', expected_revision: 2 } })
  expect(invalid.status()).toBe(422)
  const conflict = await request.put(`/api/datasets/${dataset.id}/content`, { headers, data: { content: 'null', expected_revision: 1 } })
  expect(conflict.status()).toBe(409)
  await page.goto('/dataset')
  const search = page.getByRole('textbox', { name: /^(Rechercher|Search)$/, exact: true })
  await search.fill('Synthetic')
  await page.getByRole('link', { name: 'Synthetic free JSON', exact: true }).click()
  await expect(page.getByText(dataset.uri, { exact: false })).toBeVisible()
  await expect(search).toHaveValue('Synthetic')
  await page.getByRole('textbox', { name: /^(Titre|Title)$/, exact: true }).fill('Unsaved synthetic draft')
  await page.getByRole('link', { name: other.title, exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: /^(Annuler|Cancel)$/, exact: true }).click()
  await expect(page.getByRole('textbox', { name: /^(Titre|Title)$/, exact: true })).toHaveValue('Unsaved synthetic draft')
  await expect(page).toHaveURL(new RegExp(`/dataset/${dataset.id}$`))
  await page.getByRole('link', { name: other.title, exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: /^(Abandonner les modifications|Discard changes)$/, exact: true }).click()
  await expect(page.getByRole('textbox', { name: /^(Titre|Title)$/, exact: true })).toHaveValue(other.title)
  await expect(search).toHaveValue('Synthetic')
  await page.getByRole('link', { name: 'Synthetic free JSON', exact: true }).click()
  await expect(page.getByRole('textbox', { name: /^(Titre|Title)$/, exact: true })).toHaveValue(dataset.title)
  await page.getByRole('textbox', { name: /^(Titre|Title)$/, exact: true }).fill('Synthetic renamed Dataset')
  const saved = page.waitForResponse(response => response.url().endsWith(`/datasets/${dataset.id}/content`) && response.request().method() === 'PUT')
  await page.getByRole('button', { name: /^(Enregistrer|Save)$/, exact: true }).click()
  expect((await saved).ok()).toBeTruthy()
  await expect(page.getByRole('link', { name: 'Synthetic renamed Dataset', exact: true })).toHaveAttribute('aria-current', 'page')
  await page.reload()
  await expect(page.getByRole('textbox', { name: /^(Titre|Title)$/, exact: true })).toHaveValue('Synthetic renamed Dataset')
  await expect(page.getByRole('button', { name: /^(Enregistrer|Save)$/, exact: true })).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('dataset-library-desktop.png'), fullPage: true, animations: 'disabled' })
  expect((await checked(await request.get(`/api/datasets/${dataset.id}`, { headers }))).content).toBe(written.content)
  await page.getByText(/^(Historique|History)$/, { exact: true }).first().click()
  await page.getByRole('button', { name: '1', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toContainText('accepted')
  const restored = page.waitForResponse(response => response.url().endsWith(`/datasets/${dataset.id}/revisions/1/restore`) && response.request().method() === 'POST')
  await dialog.getByRole('button', { name: /Restaurer cette révision|Restore this revision/ }).click()
  expect((await restored).ok()).toBeTruthy()
  await expect(dialog).toHaveCount(0)
  const current = await checked(await request.get(`/api/datasets/${dataset.id}`, { headers }))
  expect(current.content).toBe(source)
  expect(current.title).toBe('Synthetic renamed Dataset')
  const sharing = page.getByRole('combobox', { name: /^(Partage|Sharing)$/, exact: true })
  await expect(sharing).toContainText(/Privé|Private/)
  const sharingState = await checked(await request.get(`/api/datasets/${dataset.id}/sharing`, { headers }))
  const recipient = sharingState.options.find(option => option.kind === 'agent' && option.id === fixture.agent_id)
  expect(recipient).toBeTruthy()
  await sharing.press('Enter')
  const shared = page.waitForResponse(response => response.url().endsWith(`/datasets/${dataset.id}/sharing-level`) && response.request().method() === 'PUT')
  await page.getByRole('button', { name: `${recipient.label} : Lecture`, exact: true }).click()
  expect((await shared).ok()).toBeTruthy()
  await page.keyboard.press('Escape')
  await expect(sharing).toContainText(recipient.label)
  const latestSharing = await checked(await request.get(`/api/datasets/${dataset.id}/sharing`, { headers }))
  expect(latestSharing.grants).toEqual(expect.arrayContaining([expect.objectContaining({ kind: 'agent', id: fixture.agent_id, can_write: false })]))
  await page.getByText(/^(Utilisations|Usages)$/, { exact: true }).click()
  await expect(page.getByRole('link', { name: document.title, exact: true })).toHaveAttribute('href', `/documents?document_id=${document.id}`)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.reload()
  const title = page.getByRole('textbox', { name: /^(Titre|Title)$/, exact: true })
  await title.click()
  await expect(title).toHaveValue('Synthetic renamed Dataset')
  await expect(sharing).toContainText(recipient.label)
  await page.screenshot({ path: test.info().outputPath('dataset-editor-mobile.png'), fullPage: true, animations: 'disabled' })
  await page.getByRole('link', { name: /^(Retour à la liste|Back to list)$/, exact: true }).click()
  await expect(page.getByRole('textbox', { name: /^(Titre|Title)$/, exact: true })).toHaveCount(0)
  await page.getByRole('link', { name: 'Synthetic renamed Dataset', exact: true }).click()
  await expect(title).toHaveValue('Synthetic renamed Dataset')
  await expect(sharing).toContainText(recipient.label)
  await page.getByRole('button', { name: /^(Supprimer|Delete)$/, exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText(/processus|processes/)
  const removed = page.waitForResponse(response => response.url().includes(`/datasets/${dataset.id}?`) && response.request().method() === 'DELETE')
  await page.getByRole('dialog').getByRole('button', { name: /^(Supprimer|Delete)$/, exact: true }).click()
  expect((await removed).ok()).toBeTruthy()
  await expect(page).toHaveURL(/\/dataset$/)
  expect((await request.get(`/api/datasets/${dataset.id}`, { headers })).status()).toBe(404)
  await expect(page.getByRole('link', { name: 'Synthetic renamed Dataset', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: /^(Créer|Create)$/, exact: true }).click()
  await page.getByRole('dialog').getByRole('textbox', { name: /^(Titre|Title)$/, exact: true }).fill('Synthetic created in library')
  await page.getByRole('dialog').getByRole('button', { name: /^(Créer|Create)$/, exact: true }).click()
  await expect(title).toHaveValue('Synthetic created in library')
  await page.getByRole('link', { name: /^(Retour à la liste|Back to list)$/, exact: true }).click()
  await expect(page.getByRole('link', { name: 'Synthetic created in library', exact: true })).toBeVisible()
})
