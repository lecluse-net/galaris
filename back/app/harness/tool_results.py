"""Interpret explicit tool failures and bound history previews without changing receipts."""

from __future__ import annotations

import hashlib
import json
from typing import cast

TOOL_ERROR_SCHEMA = "galaris.tool-error/v1"

# Control fields often follow a large data field in external MCP results. Their
# order in the provider response must not decide whether pagination or failure
# remains visible in an old history preview.
_CONTROL_FIELDS = (
    "schema", "status", "outcome", "ok", "success", "isError", "code", "retryable",
    "uri", "id", "revision", "etag", "next_offset", "next_cursor", "nextCursor",
    "pageInfo", "pagination", "paging", "meta", "has_more", "hasMore",
    "hasNextPage", "endCursor", "start", "end", "total", "count", "truncated",
    "error", "encoding", "media_type", "offset_unit", "content_profile",
)


def decode_tool_result(value: object) -> object:
    """Decode JSON objects/arrays only; malformed or very deep text stays text."""
    if isinstance(value, str) and value.lstrip().startswith(("{", "[")):
        try:
            return cast(object, json.loads(value))
        except (ValueError, RecursionError):
            pass
    return value


def reported_tool_failure(value: object) -> dict[str, object] | None:
    """Recognize explicit top-level failure, never error words or business states."""
    decoded = decode_tool_result(value)
    for _ in range(4):
        if not isinstance(decoded, dict) or set(cast(dict[str, object], decoded)) != {"result", "argument_warning"}:
            break
        # The envelope generated by our execution-evidence client is distinct
        # from arbitrary provider resources or collection items.
        decoded = decode_tool_result(cast(dict[str, object], decoded)["result"])
    else:
        return None
    if not isinstance(decoded, dict):
        return None
    result = cast(dict[str, object], decoded)
    if result.get("schema") == TOOL_ERROR_SCHEMA:
        return result
    if result.get("isError") is True:
        return result
    if (result.get("ok") is False or result.get("success") is False) and result.get("error"):
        return result
    return None


def _encoded(value: object) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def _bounded_preview(value: object, budget: int, depth: int = 0) -> object:
    """Bound serialized size as well as depth and collection breadth."""
    if isinstance(value, str):
        if len(_encoded(value)) <= min(600, budget):
            return value
        digest = hashlib.sha256(value.encode("utf-8", errors="replace")).hexdigest()[:16]
        marker = f"[content omitted after execution: {len(value)} characters, sha256={digest}]"
        prefix = value[:min(600, budget // 2)]
        while prefix and len(_encoded(prefix + marker)) > budget:
            prefix = prefix[:len(prefix) // 2]
        return prefix + marker if len(_encoded(marker)) <= budget else "[omitted from history]"
    if depth >= 6:
        return "[nested content omitted from history]"
    if isinstance(value, dict):
        mapping = cast(dict[str, object], value)
        result: dict[str, object] = {}
        keys = [key for key in _CONTROL_FIELDS if key in mapping]
        keys.extend(key for key in mapping if key not in _CONTROL_FIELDS)
        for key in keys[:32]:
            remaining = budget - len(_encoded(result)) - len(_encoded(key)) - 2
            if remaining < 100:
                continue
            preview = _bounded_preview(mapping[key], remaining, depth + 1)
            candidate = {**result, key: preview}
            if len(_encoded(candidate)) <= budget:
                result = candidate
        return result
    if isinstance(value, list):
        result_list: list[object] = []
        for item in cast(list[object], value)[:4]:
            remaining = budget - len(_encoded(result_list)) - 1
            if remaining < 100:
                break
            preview = _bounded_preview(item, remaining, depth + 1)
            if len(_encoded([*result_list, preview])) <= budget:
                result_list.append(preview)
        return result_list
    return value


def compact_tool_return(value: object, *, max_chars: int = 4_000) -> object:
    """Make old results bounded and unambiguously partial, preserving raw results elsewhere."""
    decoded = decode_tool_result(value)
    try:
        serialized = value if isinstance(value, str) else _encoded(value)
    except (TypeError, ValueError, RecursionError):
        # Preserve non-JSON native/multimodal values; their SDK owns serialization.
        return value
    if len(serialized) <= max_chars:
        return value
    note = (
        "Galaris abbreviated only this model-facing preview; the original tool result "
        "remains in the execution history. Omitted content, list items and fields are not evidence of "
        "empty or missing source data, a read error, or task completion. Use retained "
        "pagination controls to continue; increasing the requested size cannot prevent "
        "history compaction. Re-read only specific missing information and retain "
        "extracted facts in durable working resources."
    )
    digest = hashlib.sha256(serialized.encode("utf-8", errors="replace")).hexdigest()[:16]
    preview = _bounded_preview(decoded, max_chars // 2)
    if isinstance(decoded, str):
        return (
            f"{preview}\n[tool result truncated after use: {len(serialized)} "
            f"characters, sha256={digest}]\n{note}"
        )
    summary: dict[str, object] = (
        dict(cast(dict[str, object], preview))
        if isinstance(preview, dict) and "history_note" not in preview
        else {"result_preview": cast(object, preview)}
    )
    summary.update(
        history_note=note, history_original_chars=len(serialized), history_sha256=digest,
        history_omission=f"[content omitted after execution: {len(serialized)} characters, sha256={digest}]",
    )
    encoded = _encoded(summary)
    return encoded if isinstance(value, str) else summary
