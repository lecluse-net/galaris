#!/usr/bin/env bash
set -euo pipefail

confirm() {
    local answer
    while true; do
        printf '%s [y/N] ' "$1"
        if ! IFS= read -r answer; then
            echo
            return 1
        fi
        case "${answer,,}" in
            y|yes|o|oui) return 0 ;;
            ''|n|no|non) return 1 ;;
            *) echo 'Please answer yes or no (oui/non).' ;;
        esac
    done
}

echo 'Uninstall removes the containers and networks of this Compose project.'
echo 'Configuration files, host-mounted directories and external databases/volumes are preserved.'
options=()

echo 'Deleting volumes permanently erases their data, including embedded PostgreSQL and stored files.'
if confirm 'Also delete the Compose-managed volumes and their data?'; then
    options+=(--volumes)
fi

echo 'Only local images generated by Compose for these services are eligible for deletion.'
echo 'Images with custom tags, including downloaded PostgreSQL/search images, are preserved.'
echo 'A later installation will rebuild local images. No forced image deletion is used.'
if confirm 'Also remove the local Compose images of this project?'; then
    options+=(--rmi local)
fi

echo 'Orphan containers belong to this Compose project but are no longer defined in its configuration.'
if confirm 'Also remove orphan containers of this project?'; then
    options+=(--remove-orphans)
fi

docker compose "$@" down "${options[@]}"
echo 'Uninstall completed with the selected cleanup options. Shared Docker build cache is preserved.'
